func testSHA256(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

// archiveEntry is one member of an archive generated by a test.
type archiveEntry struct {
	name    string
	body    string
	symlink string // a symbolic link to this target instead of a file
	dir     bool
}

func releaseTarGz(t *testing.T, entries ...archiveEntry) []byte {
	t.Helper()
	var buffer bytes.Buffer
	compressed := gzip.NewWriter(&buffer)
	writer := tar.NewWriter(compressed)
	for _, entry := range entries {
		header := &tar.Header{Name: entry.name, Mode: 0o755, Size: int64(len(entry.body)), Typeflag: tar.TypeReg}
		switch {
		case entry.dir:
			header.Typeflag, header.Size = tar.TypeDir, 0
		case entry.symlink != "":
			header.Typeflag, header.Size, header.Linkname = tar.TypeSymlink, 0, entry.symlink
		}
		if err := writer.WriteHeader(header); err != nil {
			t.Fatal(err)
		}
		if header.Typeflag == tar.TypeReg {
			if _, err := writer.Write([]byte(entry.body)); err != nil {
				t.Fatal(err)
			}
		}
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	if err := compressed.Close(); err != nil {
		t.Fatal(err)
	}
	return buffer.Bytes()
}

func releaseZip(t *testing.T, entries ...archiveEntry) []byte {
	t.Helper()
	var buffer bytes.Buffer
	writer := zip.NewWriter(&buffer)
	for _, entry := range entries {
		header := &zip.FileHeader{Name: entry.name, Method: zip.Deflate}
		body := entry.body
		if entry.symlink != "" {
			header.SetMode(os.ModeSymlink | 0o777)
			body = entry.symlink
		} else {
			header.SetMode(0o755)
		}
		file, err := writer.CreateHeader(header)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := file.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	return buffer.Bytes()
}

// fakeRelease serves release downloads the way github.com lays them out,
// /<owner>/<repo>/releases/download/<tag>/<asset>, and points releaseBaseURL
// at itself for the test, so no test ever reaches GitHub.
type fakeRelease struct {
	mu       sync.Mutex
	files    map[string][]byte
	redirect map[string]string
	hits     map[string]int
}

func newFakeRelease(t *testing.T) *fakeRelease {
	t.Helper()
	release := &fakeRelease{files: map[string][]byte{}, redirect: map[string]string{}, hits: map[string]int{}}
	const prefix = "/" + releaseRepository + "/releases/download/"
	server := httptest.NewServer(http.HandlerFunc(func(writer http.ResponseWriter, request *http.Request) {
		key, ok := strings.CutPrefix(request.URL.Path, prefix)
		release.mu.Lock()
		release.hits[key]++
		body, found := release.files[key]
		target := release.redirect[key]
		release.mu.Unlock()
		switch {
		case target != "":
			http.Redirect(writer, request, target, http.StatusFound)
		case !ok || !found:
			http.NotFound(writer, request)
		default:
			_, _ = writer.Write(body)
		}
	}))
	t.Cleanup(server.Close)
	saved := releaseBaseURL
	releaseBaseURL = server.URL + "/" + releaseRepository + "/releases"
	t.Cleanup(func() { releaseBaseURL = saved })
	return release
}

func (release *fakeRelease) add(tag, name string, body []byte) {
	release.mu.Lock()
	defer release.mu.Unlock()
	release.files[tag+"/"+name] = body
}

func (release *fakeRelease) remove(tag, name string) {
	release.mu.Lock()
	defer release.mu.Unlock()
	delete(release.files, tag+"/"+name)
}

func (release *fakeRelease) file(tag, name string) []byte {
	release.mu.Lock()
	defer release.mu.Unlock()
	return release.files[tag+"/"+name]
}

func (release *fakeRelease) hitCount(tag, name string) int {
	release.mu.Lock()
	defer release.mu.Unlock()
	return release.hits[tag+"/"+name]
}

func (release *fakeRelease) totalHits() int {
	release.mu.Lock()
	defer release.mu.Unlock()
	total := 0
	for _, count := range release.hits {
		total += count
	}
	return total
}

// publish serves the assets and a SHA256SUMS that lists every one of them.
func (release *fakeRelease) publish(tag string, assets map[string][]byte) {
	var sums strings.Builder
	for _, name := range sortedKeys(assets) {
		release.add(tag, name, assets[name])
		fmt.Fprintf(&sums, "%s  %s\n", testSHA256(assets[name]), name)
	}
	release.add(tag, releaseSumsName, []byte(sums.String()))
}

func TestReleasePlatformSelection(t *testing.T) {
	published, err := parseSHA256Sums([]byte(publishedSums062))
	if err != nil {
		t.Fatal(err)
	}
	cases := []struct {
		goOS, goArch, flavor     string
		platform, target, binary string
	}{
		{"linux", "amd64", "", "linux-x86_64-musl-direct", "x86_64-unknown-linux-musl", "rarpar"},
		{"linux", "amd64", FlavorMuslDirect, "linux-x86_64-musl-direct", "x86_64-unknown-linux-musl", "rarpar"},
		{"linux", "amd64", FlavorGNUDirect, "linux-x86_64-gnu-direct", "x86_64-unknown-linux-gnu", "rarpar"},
		{"linux", "arm64", "", "linux-arm64-musl-direct", "aarch64-unknown-linux-musl", "rarpar"},
		{"linux", "arm64", FlavorGNUDirect, "linux-arm64-gnu-direct", "aarch64-unknown-linux-gnu", "rarpar"},
		{"darwin", "arm64", "", "darwin-arm64", "aarch64-apple-darwin", "rarpar"},
		{"darwin", "amd64", "", "darwin-x86_64", "x86_64-apple-darwin", "rarpar"},
		{"windows", "amd64", "", "windows-x86_64", "x86_64-pc-windows-msvc", "rarpar.exe"},
		{"windows", "arm64", "", "windows-arm64", "aarch64-pc-windows-msvc", "rarpar.exe"},
	}
	covered := map[string]bool{}
	for _, tc := range cases {
		platform, err := resolveReleasePlatform(Bundle{GoOS: tc.goOS, GoArch: tc.goArch, Flavor: tc.flavor})
		if err != nil {
			t.Fatalf("%s/%s flavor %q: %v", tc.goOS, tc.goArch, tc.flavor, err)
		}
		archive := "tar.gz"
		if tc.goOS == "windows" {
			archive = "zip"
		}
		if platform.Name != tc.platform || platform.RustTarget != tc.target || platform.Binary != tc.binary || platform.Archive != archive {
			t.Fatalf("%s/%s flavor %q resolved to %+v", tc.goOS, tc.goArch, tc.flavor, platform)
		}
		asset := releaseAssetName("rarpar-v0.6.2", platform)
		if _, ok := published[asset]; !ok {
			t.Fatalf("%s/%s flavor %q picks %s, which the v0.6.2 release does not publish", tc.goOS, tc.goArch, tc.flavor, asset)
		}
		covered[asset] = true
	}
	if len(covered) != len(published) {
		t.Fatalf("selection reaches %d of the %d published assets", len(covered), len(published))
	}

	refusals := []struct {
		bundle Bundle
		want   string
	}{
		{Bundle{GoOS: "linux"}, "bundle.go_arch is required to pick the release asset"},
		{Bundle{GoOS: "linux", GoArch: "386"}, `bundle.go_arch = "386" has no rarpar release asset`},
		{Bundle{GoOS: "linux", GoArch: "amd64", Flavor: "static"}, `bundle.flavor must be "musl-direct" (the default) or "gnu-direct", got "static"`},
		{Bundle{GoOS: "windows", GoArch: "amd64", Flavor: FlavorMuslDirect}, "bundle.flavor only applies to linux release assets"},
		{Bundle{GoOS: "darwin", GoArch: "arm64", Flavor: FlavorGNUDirect}, "bundle.flavor only applies to linux release assets"},
		{Bundle{GoOS: "freebsd", GoArch: "amd64"}, `bundle.go_os = "freebsd" has no rarpar release asset`},
	}
	for _, tc := range refusals {
		if _, err := resolveReleasePlatform(tc.bundle); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Fatalf("%+v: error %v does not mention %q", tc.bundle, err, tc.want)
		}
	}
}

func TestReleaseTagShape(t *testing.T) {
	for _, tc := range []struct {
		bundle Bundle
		want   string
	}{
		{Bundle{Tag: "rarpar-v0.6.2"}, "rarpar-v0.6.2"},
		{Bundle{Version: "0.6.2"}, "rarpar-v0.6.2"},
		{Bundle{Version: "v0.6.2"}, "rarpar-v0.6.2"},
		{Bundle{}, ""},
	} {
		if got := tc.bundle.releaseTag(); got != tc.want {
			t.Fatalf("%+v names release %q, want %q", tc.bundle, got, tc.want)
		}
	}
	for _, tag := range []string{"rarpar-v0.6.2", "rarpar-v0.7.0", "rarpar-v1.0.0-rc.1"} {
		if !releaseTagPattern.MatchString(tag) {
			t.Fatalf("%s is a release tag", tag)
		}
	}
	// The tag becomes a URL path segment and a cache directory name.
	for _, tag := range []string{"v0.6.2", "rarpar-0.6.2", "rarpar-v0.6", "rarpar-v0.6.2/../../x", "../rarpar-v0.6.2", "rarpar-v0.6.2-", "rarpar-v0.6.2 ", "rarpar-v0.6.2-../x"} {
		if releaseTagPattern.MatchString(tag) {
			t.Fatalf("%q must not pass as a release tag", tag)
		}
	}
}

func TestParseSHA256Sums(t *testing.T) {
	digest := strings.Repeat("ab", 32)
	parsed, err := parseSHA256Sums([]byte(digest + "  one.tar.gz\r\n\n" + strings.ToUpper(digest) + " *two.zip\n"))
	if err != nil {
		t.Fatal(err)
	}
	if len(parsed) != 2 || parsed["one.tar.gz"] != digest || parsed["two.zip"] != digest {
		t.Fatalf("text and binary mode lines must both parse, digests lowercased: %v", parsed)
	}
	published, err := parseSHA256Sums([]byte(publishedSums062))
	if err != nil {
		t.Fatal(err)
	}
	if len(published) != 8 || published["rarpar-rarpar-v0.6.2-windows-x86_64.zip"] != "02b3657fbdee3bc141f0d9ec43776a1d2539f09fe6038e010c6d5021778a711f" {
		t.Fatalf("the published v0.6.2 manifest parsed to %v", published)
	}
	// A damaged manifest is refused outright rather than read around: a
	// skipped line could be the asset under test.
	for name, manifest := range map[string]string{
		"one space":          digest + " one.tar.gz\n",
		"short digest":       digest[:62] + "  one.tar.gz\n",
		"not hex":            strings.Repeat("zz", 32) + "  one.tar.gz\n",
		"no file name":       digest + "  \n",
		"path in the name":   digest + "  dir/one.tar.gz\n",
		"trailing space":     digest + "  one.tar.gz \n",
		"listed twice":       digest + "  one.tar.gz\n" + digest + "  one.tar.gz\n",
		"no entries":         "\n\n",
		"a line of anything": digest + "  one.tar.gz\nnot a sums line\n",
	} {
		if _, err := parseSHA256Sums([]byte(manifest)); err == nil {
			t.Fatalf("%s: the manifest must be refused", name)
		}
	}
}

func TestReleaseResolverStagesTheLinuxTarball(t *testing.T) {
	release := newFakeRelease(t)
	const tag = "rarpar-v1.2.3"
	const binary = "\x7fELF stand-in rarpar"
	// The published tarballs carry the bash completion, also named rarpar,
	// ahead of the binary.
	tarball := releaseTarGz(t,
		archiveEntry{name: "./", dir: true},
		archiveEntry{name: "./share/bash-completion/completions/rarpar", body: "complete -F _rarpar rarpar"},
		archiveEntry{name: "./rarpar", body: binary},
	)
	asset := "rarpar-" + tag + "-linux-x86_64-musl-direct.tar.gz"
	release.publish(tag, map[string][]byte{
		asset:                                   tarball,
		"rarpar-" + tag + "-windows-x86_64.zip": releaseZip(t, archiveEntry{name: "rarpar.exe", body: "MZ"}),
	})
	cache := t.TempDir()
	bundle := Bundle{Source: BundleRelease, Tag: tag, GoOS: "linux", GoArch: "amd64"}
	resolver := newReleaseResolver(cache, t.Logf)
	artifact, err := resolver.resolve(t.Context(), bundle)
	if err != nil {
		t.Fatal(err)
	}
	staged, err := os.ReadFile(artifact.binaryPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(staged) != binary {
		t.Fatalf("staged %q: the bash completion must not be mistaken for the binary", staged)
	}
	if info, err := os.Stat(artifact.binaryPath); err != nil || info.Mode().Perm() != 0o755 {
		t.Fatalf("the staged binary must be executable: %v %v", info, err)
	}
	if artifact.Repository != releaseRepository || artifact.Tag != tag || artifact.Platform != "linux-x86_64-musl-direct" ||
		artifact.RustTarget != "x86_64-unknown-linux-musl" || artifact.Asset != asset ||
		artifact.Size != int64(len(tarball)) || artifact.SHA256 != testSHA256(tarball) ||
		artifact.Binary != "rarpar" || artifact.BinarySHA256 != testSHA256([]byte(binary)) || artifact.BinarySize != int64(len(binary)) {
		t.Fatalf("provenance does not describe the asset: %+v", artifact)
	}
	if artifact.AssetURL != releaseBaseURL+"/download/"+tag+"/"+asset || artifact.ReleaseURL != releaseBaseURL+"/tag/"+tag ||
		artifact.SumsURL != releaseBaseURL+"/download/"+tag+"/SHA256SUMS" || artifact.SumsSHA256 != testSHA256(release.file(tag, releaseSumsName)) {
		t.Fatalf("provenance does not name where the asset came from: %+v", artifact)
	}
	kept, err := os.ReadFile(filepath.Join(cache, tag, releaseSumsName))
	if err != nil || !bytes.Equal(kept, release.file(tag, releaseSumsName)) {
		t.Fatalf("SHA256SUMS must be kept beside the assets it vouches for: %v", err)
	}
	if _, err := os.Stat(filepath.Join(cache, tag, artifact.Platform, asset+".part")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("no partial download may be left behind: %v", err)
	}

	// Once per (tag, platform): another machine on the platform, however it
	// names the release, reuses the resolution.
	again, err := resolver.resolve(t.Context(), Bundle{Source: BundleRelease, Version: "1.2.3", GoOS: "linux", GoArch: "amd64", Flavor: FlavorMuslDirect})
	if err != nil {
		t.Fatal(err)
	}
	if again != artifact || release.hitCount(tag, asset) != 1 || release.hitCount(tag, releaseSumsName) != 1 {
		t.Fatalf("a second machine on the platform must not download again (asset %d, sums %d)",
			release.hitCount(tag, asset), release.hitCount(tag, releaseSumsName))
	}
	// A later run over the same cache fetches SHA256SUMS fresh and re-hashes
	// the cached asset instead of downloading it again.
	if _, err := newReleaseResolver(cache, t.Logf).resolve(t.Context(), bundle); err != nil {
		t.Fatal(err)
	}
	if release.hitCount(tag, asset) != 1 || release.hitCount(tag, releaseSumsName) != 2 {
		t.Fatalf("a cached asset is re-hashed, not re-downloaded (asset %d, sums %d)",
			release.hitCount(tag, asset), release.hitCount(tag, releaseSumsName))
	}
}

