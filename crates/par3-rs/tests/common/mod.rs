/// The set's input blocks, rebuilt from the file contents the way the reference
/// loads them.
///
/// Every chunk contributes `length / block_size` whole blocks from
/// `first_block_index` onwards, in file order. A chunk whose length is not a
/// whole number of blocks ends in a tail: a described tail goes to the block and
/// offset the chunk names, and the rest of that block stays zero; an inline tail
/// lives in the File packet and occupies no block at all.
pub fn input_blocks(set: &Par3Set, contents: &[(&str, Vec<u8>)]) -> BTreeMap<u64, Vec<u8>> {
    let block_size = usize::try_from(set.block_size()).expect("a sane block size");
    let mut blocks: BTreeMap<u64, Vec<u8>> = BTreeMap::new();

    for file in set.files() {
        let data = contents
            .iter()
            .find(|(path, _)| *path == file.path())
            .unwrap_or_else(|| panic!("no contents supplied for {}", file.path()))
            .1
            .as_slice();
        let mut chunk_offset = 0usize;
        for chunk in file.chunks() {
            let ChunkDescription::Protected {
                length,
                first_block_index,
                tail,
            } = chunk
            else {
                panic!("the oracle archives contain no unprotected chunks");
            };
            let length = usize::try_from(*length).expect("a sane chunk length");
            let full_blocks = length / block_size;
            for step in 0..full_blocks {
                let first = first_block_index.expect("a chunk of a block or more names its first");
                let index = first + step as u64;
                let start = chunk_offset + step * block_size;
                let previous = blocks.insert(index, data[start..start + block_size].to_vec());
                assert!(previous.is_none(), "input block {index} was claimed twice");
            }
            if let ChunkTail::Described {
                block_index,
                offset,
                ..
            } = tail
            {
                let tail_length = length % block_size;
                let start = chunk_offset + full_blocks * block_size;
                let at = usize::try_from(*offset).expect("a sane tail offset");
                // Tail packing is off in these oracles, so a tail block holds one
                // tail and nothing else; anything already there means the map is
                // wrong and whatever is computed from it would only be confusing.
                let mut block = vec![0u8; block_size];
                block[at..at + tail_length].copy_from_slice(&data[start..start + tail_length]);
                let previous = blocks.insert(*block_index, block);
                assert!(
                    previous.is_none(),
                    "input block {block_index} was claimed twice"
                );
            }
            chunk_offset += length;
        }
    }
    blocks
}

/// Compare two blocks, naming the first byte that differs rather than printing
/// thousands of them.
pub fn assert_block_eq(actual: &[u8], expected: &[u8], what: &str) {
    if actual == expected {
        return;
    }
    assert_eq!(
        actual.len(),
        expected.len(),
        "{what}: length {} but expected {}",
        actual.len(),
        expected.len()
    );
    let at = actual
        .iter()
        .zip(expected)
        .position(|(a, b)| a != b)
        .expect("the blocks differ somewhere");
    let differing = actual.iter().zip(expected).filter(|(a, b)| a != b).count();
    panic!(
        "{what}: first difference at byte {at} ({:#04x} in the packet, {:#04x} computed); \
         {differing} of {} bytes differ",
        actual[at],
        expected[at],
        actual.len()
    );
}

/// A scratch directory under the system temp directory, removed when the test
/// that made it finishes.
///
/// Setting `PAR3_KEEP_OUTPUT` in the environment keeps it instead, and the path
/// is printed so the files can be looked at; `cargo test -- --nocapture` shows
/// it.
pub struct TempTree {
    path: std::path::PathBuf,
    keep: bool,
}

impl TempTree {
    /// Make a fresh directory named after the test using it.
    pub fn new(label: &str) -> Self {
        use std::sync::atomic::{AtomicU64, Ordering};
        static COUNTER: AtomicU64 = AtomicU64::new(0);

        let unique = COUNTER.fetch_add(1, Ordering::Relaxed);
        let path =
            std::env::temp_dir().join(format!("par3-rs-{label}-{}-{unique}", std::process::id()));
        std::fs::create_dir_all(&path).expect("a scratch directory");
        let keep = std::env::var_os("PAR3_KEEP_OUTPUT").is_some();
        if keep {
            println!("PAR3_KEEP_OUTPUT: keeping {}", path.display());
        }
        Self { path, keep }
    }

    /// Where the directory is.
    pub fn path(&self) -> &std::path::Path {
        &self.path
    }

    /// Put a file in it, making the directories above it first.
    pub fn write(&self, name: &str, data: &[u8]) -> std::path::PathBuf {
        let path = self.path.join(name);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).expect("a parent directory");
        }
        std::fs::write(&path, data).expect("a written file");
        path
    }

    /// Make an empty directory in it.
    pub fn mkdir(&self, name: &str) {
        std::fs::create_dir_all(self.path.join(name)).expect("a directory");
    }

    /// Read one of its files back.
    pub fn read(&self, name: &str) -> Vec<u8> {
        std::fs::read(self.path.join(name)).expect("a readable file")
    }
}

impl Drop for TempTree {
    fn drop(&mut self) {
        if !self.keep {
            let _ = std::fs::remove_dir_all(&self.path);
        }
    }
}

/// Write the GF(2^8) oracle's three input files into a scratch directory.
pub fn write_gf8_inputs(tree: &TempTree) {
    tree.write("a.bin", &a_bin());
    tree.write("b.txt", &b_txt());
    tree.write("sub/c.bin", &c_bin());
}

/// Write the GF(2^16) oracle's one input file into a scratch directory.
pub fn write_gf16_inputs(tree: &TempTree) {
    tree.write("big.bin", &big_bin());
}

/// The eight-byte type signature of a packet, as text, for readable failures.
pub fn type_name(packet: &Packet) -> String {
    String::from_utf8_lossy(&packet.packet_type().signature())
        .trim_end_matches('\0')
        .to_owned()
}

/// The type signatures of a file's packets, in the order they were written.
pub fn type_sequence(data: &[u8]) -> Vec<String> {
    packets_of(data).iter().map(type_name).collect()
}

/// The body bytes of a packet: everything after the 48-byte header.
pub fn body_of(packet: &Packet) -> Vec<u8> {
    packet.to_bytes()[48..].to_vec()
}
