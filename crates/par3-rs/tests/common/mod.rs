//! Bytes the reference implementation produced, shared by the oracle tests.
//!
//! # Provenance
//!
//! The six `.par3` files embedded below were created by the official
//! `par3cmdline` at commit `2971702e501f1350b1c7b9d11369af9157d6ed56`, built and
//! run inside a Debian bookworm container on native linux/arm64 (no emulation).
//! The build used the project's own CMake setup:
//!
//! ```text
//! cmake -D CMAKE_BUILD_TYPE=Release -G Ninja -S src -B build-linux
//! cmake --build build-linux
//! ```
//!
//! with two source changes needed only to compile on arm64: the bundled BLAKE3
//! was restricted to its portable backend, and the bundled Leopard codec was
//! given an `sse2neon` shim. Neither affects the bytes of a `.par3` file.
//!
//! The archives were then created with:
//!
//! ```text
//! par3 create -B<in> -s2000 -c2 -R -v -C"rarpar oracle" set.par3 a.bin b.txt sub
//! par3 create -B<in16> -s100 -c3 -v -C"rarpar oracle gf16" set16.par3 big.bin
//! ```
//!
//! Each run wrote an index file and one `.volXX+YY.par3` recovery volume per
//! group of recovery blocks. All six files are embedded here, index and volumes
//! alike, each with the size and the first sixteen bytes of the BLAKE3 digest of
//! the file it was taken from, so that a future reader can re-check the constant
//! against the artefact.
//!
//! The input files are regenerated from the formulas they were made with rather
//! than embedded, and every damage case flips or truncates bytes of those
//! regenerated inputs or of an in-memory copy of a `.par3` file. No PAR3 bytes
//! here were assembled or edited by hand: they are exactly what the reference
//! implementation wrote.

