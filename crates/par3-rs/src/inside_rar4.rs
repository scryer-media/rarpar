fn crc32(bytes: &[u8]) -> u32 {
    let mut crc = Digest::new(CrcAlgorithm::Crc32IsoHdlc);
    crc.update(bytes);
    crc.finalize() as u32
}

fn crc_table() -> &'static [u32; 256] {
    static TABLE: std::sync::OnceLock<[u32; 256]> = std::sync::OnceLock::new();
    TABLE.get_or_init(|| {
        let mut table = [0u32; 256];
        for (index, entry) in table.iter_mut().enumerate() {
            let mut value = index as u32;
            for _ in 0..8 {
                value = if value & 1 != 0 {
                    (value >> 1) ^ 0xEDB8_8320
                } else {
                    value >> 1
                };
            }
            *entry = value;
        }
        table
    })
}

/// Advance a raw (not inverted) CRC32 register over `bytes`.
fn crc_update(mut state: u32, bytes: &[u8]) -> u32 {
    let table = crc_table();
    for &byte in bytes {
        state = table[((state ^ u32::from(byte)) & 0xff) as usize] ^ (state >> 8);
    }
    state
}

/// The sixteen bytes `x` with `eval(x) == target`, for an `eval` that is
/// affine over GF(2) in `x` (a CRC32 of bytes that include `x`, and of fields
/// that are themselves CRCs of `x`).
fn solve_affine(eval: &dyn Fn(&[u8; 16]) -> u32, target: u32) -> EngineResult<[u8; 16]> {
    let at = |x: u128| eval(&x.to_le_bytes());
    let base = at(0);
    let columns: Vec<u32> = (0..128).map(|bit| at(1u128 << bit) ^ base).collect();
    let mut rows: Vec<(u128, u32)> = Vec::new();
    for bit in 0..32 {
        let mut mask = 0u128;
        for (column, value) in columns.iter().enumerate() {
            if (value >> bit) & 1 == 1 {
                mask |= 1 << column;
            }
        }
        rows.push((mask, ((target ^ base) >> bit) & 1));
    }
    let mut pivots: Vec<(u32, u128, u32)> = Vec::new();
    for (mut mask, mut rhs) in rows {
        for &(column, pivot_mask, pivot_rhs) in &pivots {
            if (mask >> column) & 1 == 1 {
                mask ^= pivot_mask;
                rhs ^= pivot_rhs;
            }
        }
        if mask == 0 {
            if rhs != 0 {
                return Err(EngineError::Unsupported("CRC compensation has no solution"));
            }
            continue;
        }
        let column = mask.trailing_zeros();
        for pivot in &mut pivots {
            if (pivot.1 >> column) & 1 == 1 {
                pivot.1 ^= mask;
                pivot.2 ^= rhs;
            }
        }
        pivots.push((column, mask, rhs));
    }
    let mut x = 0u128;
    for (column, _, rhs) in pivots {
        if rhs == 1 {
            x |= 1 << column;
        }
    }
    let bytes = x.to_le_bytes();
    if eval(&bytes) != target {
        return Err(EngineError::InvalidState("CRC compensation check"));
    }
    Ok(bytes)
}

fn push_vint(out: &mut Vec<u8>, mut value: u64) {
    loop {
        let byte = (value & 0x7f) as u8;
        value >>= 7;
        if value == 0 {
            out.push(byte);
            return;
        }
        out.push(byte | 0x80);
    }
}

fn read_vint(bytes: &[u8], at: &mut usize) -> EngineResult<u64> {
    let mut value = 0u64;
    for shift in (0..70).step_by(7) {
        let byte = *bytes
            .get(*at)
            .ok_or(EngineError::Unsupported("truncated RAR5 header field"))?;
        *at += 1;
        if shift == 63 && byte > 1 {
            return Err(EngineError::Unsupported("oversized RAR5 header field"));
        }
        value |= u64::from(byte & 0x7f) << shift;
        if byte & 0x80 == 0 {
            return Ok(value);
        }
    }
    Err(EngineError::Unsupported("oversized RAR5 header field"))
}

fn u16_at(bytes: &[u8], at: usize) -> EngineResult<u16> {
    bytes
        .get(at..at + 2)
        .map(|b| u16::from_le_bytes([b[0], b[1]]))
        .ok_or(EngineError::Unsupported("truncated RAR4 header"))
}

fn u32_at(bytes: &[u8], at: usize) -> EngineResult<u32> {
    bytes
        .get(at..at + 4)
        .map(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]))
        .ok_or(EngineError::Unsupported("truncated RAR4 header"))
}

/// The plain RAR4 `NEWSUB` header of a region.
fn rar4_header(carrier: u64, encrypted: bool, file_crc: u32, tail: &[u8; 8]) -> Vec<u8> {
    let mut flags = LONG_BLOCK | SKIP_IF_UNKNOWN;
    if encrypted {
        flags |= LHD_PASSWORD | LHD_SALT;
    }
    let size: u16 = 44;
    let (pack, unpacked) = if encrypted {
        (align16(carrier) + 16, carrier)
    } else {
        (carrier + 8, carrier + 8)
    };
    let mut h = vec![0, 0, NEWSUB];
    h.extend_from_slice(&flags.to_le_bytes());
    h.extend_from_slice(&size.to_le_bytes());
    h.extend_from_slice(&(pack as u32).to_le_bytes());
    h.extend_from_slice(&(unpacked as u32).to_le_bytes());
    h.push(3); // HOST_OS Unix, as rar writes for its own NEWSUB blocks.
    h.extend_from_slice(&file_crc.to_le_bytes());
    h.extend_from_slice(&0u32.to_le_bytes()); // FTIME
    h.push(29); // UNP_VER
    h.push(0x30); // METHOD store
    h.extend_from_slice(&(SERVICE_NAME.len() as u16).to_le_bytes());
    h.extend_from_slice(&0u32.to_le_bytes()); // ATTR
    h.extend_from_slice(SERVICE_NAME);
    // The salt when encrypted; otherwise eight bytes of sub-block data
    // (`SubData`) that keep `EARC_DATACRC` valid.
    h.extend_from_slice(tail);
    let crc = (crc32(&h[2..]) & 0xffff) as u16;
    h[..2].copy_from_slice(&crc.to_le_bytes());
    h
}

/// The plain RAR5 service header (CRC, size and fields) of an encrypted
/// region, with a file-encryption extra record.
fn rar5_service_plain(carrier: u64, salt: &[u8; 16], lg2: u8, iv: &[u8; 16]) -> Vec<u8> {
    let mut record = Vec::new();
    push_vint(&mut record, 1); // FHEXTRA_CRYPT
    push_vint(&mut record, 0); // version
    push_vint(&mut record, 0); // flags: no password check, no MAC
    record.push(lg2);
    record.extend_from_slice(salt);
    record.extend_from_slice(iv);
    let mut extra = Vec::new();
    push_vint(&mut extra, record.len() as u64);
    extra.extend_from_slice(&record);
    let mut inner = Vec::new();
    push_vint(&mut inner, 3);
    push_vint(&mut inner, 0x1 | 0x2 | 0x4);
    push_vint(&mut inner, extra.len() as u64);
    push_vint(&mut inner, align16(carrier));
    push_vint(&mut inner, 0); // file flags
    push_vint(&mut inner, carrier); // unpacked size
    push_vint(&mut inner, 0); // attributes
    push_vint(&mut inner, 0); // compression: stored
    push_vint(&mut inner, 1); // host OS Unix
    push_vint(&mut inner, SERVICE_NAME.len() as u64);
    inner.extend_from_slice(SERVICE_NAME);
    inner.extend_from_slice(&extra);
    let mut sized = Vec::new();
    push_vint(&mut sized, inner.len() as u64);
    sized.extend_from_slice(&inner);
    let mut out = crc32(&sized).to_le_bytes().to_vec();
    out.extend_from_slice(&sized);
    out
}

fn derive(id: InputSetId, host: usize, tag: &[u8]) -> [u8; 32] {
    let mut hasher = blake3::Hasher::new();
    hasher.update(b"par3-rs experimental PAR-inside RAR region");
    hasher.update(&id.0);
    hasher.update(&(host as u64).to_le_bytes());
    hasher.update(tag);
    *hasher.finalize().as_bytes()
}

fn first<const N: usize>(bytes: [u8; 32]) -> [u8; N] {
    bytes[..N].try_into().expect("prefix")
}

fn pad16(bytes: &[u8]) -> Vec<u8> {
    let mut out = bytes.to_vec();
    out.resize(align16(bytes.len() as u64) as usize, 0);
    out
}

/// What rendering a host's region needs besides the carrier.
#[derive(Clone, Debug, Default)]
struct HostCtx {
    /// RAR4 `EARC_DATACRC` the region has to keep valid.
    data_crc: Option<u32>,
    /// RAR5 header key.
    rar5_key: Option<Rar5Key>,
}

/// The region bytes for `carrier` in host `host` of set `id`. `body` is the
/// raw CRC32 register over the host bytes before the region.
fn render(
    spec: Spec,
    crypto: Option<&Crypto>,
    id: InputSetId,
    host: usize,
    ctx: &HostCtx,
    body: u32,
    carrier: &[u8],
) -> EngineResult<Vec<u8>> {
    let c = carrier.len() as u64;
    // Experiment knob: leave `EARC_DATACRC` stale, to observe readers.
    let stale = std::env::var_os("PAR3_RAR4_EXPERIMENT_STALE_DATACRC").is_some();
    let ctx = &HostCtx {
        data_crc: ctx.data_crc.filter(|_| !stale),
        rar5_key: ctx.rar5_key,
    };
    let need = || EngineError::Unsupported("encrypted headers need the password");
    let region = match (spec.layout, spec.format, spec.encrypted) {
        (Layout::Trailing, ..) => carrier.to_vec(),
        (Layout::Service, Format::Rar4, false) => {
            if c + 8 > u64::from(u32::MAX) {
                return Err(EngineError::Unsupported("RAR4 region too large"));
            }
            // Sixteen free bytes: eight of sub-block data at the end of the
            // header and eight after the carrier. FILE_CRC covers the data
            // area, and HEAD_CRC covers FILE_CRC and the sub-block data, so
            // the archive CRC is affine in all sixteen; free bytes in the
            // header alone are not always enough.
            let mut data = carrier.to_vec();
            data.extend_from_slice(&[0; 8]);
            let build = |free: &[u8; 16], data: &mut Vec<u8>| {
                let n = data.len();
                data[n - 8..].copy_from_slice(&free[8..]);
                let sub: [u8; 8] = free[..8].try_into().expect("sub");
                rar4_header(c, false, crc32(data), &sub)
            };
            let free = match ctx.data_crc {
                None => [0; 16],
                Some(target) => {
                    let scratch = std::cell::RefCell::new(data.clone());
                    let eval = |free: &[u8; 16]| {
                        let mut data = scratch.borrow_mut();
                        let header = build(free, &mut data);
                        !crc_update(crc_update(body, &header), &data)
                    };
                    solve_affine(&eval, target)?
                }
            };
            let mut out = build(&free, &mut data);
            out.extend_from_slice(&data);
            out
        }
        (Layout::Service, Format::Rar4, true) => {
            if align16(c) + 16 > u64::from(u32::MAX) {
                return Err(EngineError::Unsupported("RAR4 region too large"));
            }
            let crypto = crypto.ok_or_else(need)?;
            let header_salt: [u8; 8] = first(derive(id, host, b"rar4 header salt"));
            let data_salt: [u8; 8] = first(derive(id, host, b"rar4 data salt"));
            let (header_key, header_iv) = crypto.rar4(&header_salt);
            let (data_key, data_iv) = crypto.rar4(&data_salt);
            let header = rar4_header(c, true, crc32(carrier), &data_salt);
            let mut header = pad16(&header);
            crypto.encrypt(&header_key, &header_iv, &mut header);
            let mut data = pad16(carrier);
            crypto.encrypt(&data_key, &data_iv, &mut data);
            let mut out = header_salt.to_vec();
            out.extend_from_slice(&header);
            out.extend_from_slice(&data);
            out.extend_from_slice(&[0; 16]);
            if let Some(target) = ctx.data_crc {
                let len = out.len();
                let state = crc_update(body, &out[..len - 16]);
                let x = solve_affine(&|x: &[u8; 16]| !crc_update(state, x), target)?;
                out[len - 16..].copy_from_slice(&x);
            }
            out
        }
        (Layout::Service, Format::Rar5, false) => {
            let mut out = r5::region_header(r5::Rar5Layout::Service, c);
            out.extend_from_slice(carrier);
            out
        }
        (Layout::Service, Format::Rar5, true) => {
            let crypto = crypto.ok_or_else(need)?;
            let (key, salt, lg2) = ctx
                .rar5_key
                .ok_or(EngineError::Unsupported("RAR5 encryption header not found"))?;
            let header_iv: [u8; 16] = first(derive(id, host, b"rar5 header iv"));
            let data_iv: [u8; 16] = first(derive(id, host, b"rar5 data iv"));
            let mut header = pad16(&rar5_service_plain(c, &salt, lg2, &data_iv));
            crypto.encrypt(&key, &header_iv, &mut header);
            let mut data = pad16(carrier);
            crypto.encrypt(&key, &data_iv, &mut data);
            let mut out = header_iv.to_vec();
            out.extend_from_slice(&header);
            out.extend_from_slice(&data);
            out
        }
    };
    if region.len() as u64 != spec.gap(c) {
        return Err(EngineError::InvalidState("rendered region length"));
    }
    Ok(region)
}

type ReadFn<'a> = dyn Fn(u64, &mut [u8]) -> EngineResult<()> + 'a;

fn find_signature(read: &ReadFn<'_>, length: u64) -> EngineResult<(Format, u64)> {
    let probe = length.min(SFX_LIMIT + 8) as usize;
    let mut head = vec![0; probe];
    read(0, &mut head)?;
    let rar5 = head.windows(SIG5.len()).position(|w| w == SIG5);
    let rar4 = head.windows(SIG4.len()).position(|w| w == SIG4);
    match (rar4, rar5) {
        (Some(old), Some(new)) if old < new => Ok((Format::Rar4, old as u64)),
        (_, Some(new)) => Ok((Format::Rar5, new as u64)),
        (Some(old), None) => Ok((Format::Rar4, old as u64)),
        (None, None) => Err(EngineError::Unsupported("not a RAR archive")),
    }
}

/// Read one RAR4 header at `at`: the plain header bytes (`HEAD_SIZE` of them)
/// and its length on disk.
fn rar4_header_at(
    read: &ReadFn<'_>,
    at: u64,
    length: u64,
    crypto: Option<&Crypto>,
) -> EngineResult<(Vec<u8>, u64)> {
    let truncated = EngineError::Unsupported("truncated RAR4 header");
    let header = match crypto {
        None => {
            if length.saturating_sub(at) < 7 {
                return Err(truncated);
            }
            let mut lead = [0u8; 7];
            read(at, &mut lead)?;
            let size = u64::from(u16::from_le_bytes([lead[5], lead[6]]));
            if size < 7 || at + size > length {
                return Err(truncated);
            }
            let mut header = vec![0; size as usize];
            read(at, &mut header)?;
            (header, size)
        }
        Some(crypto) => {
            if length.saturating_sub(at) < 8 + 16 {
                return Err(truncated);
            }
            let mut salt = [0u8; 8];
            read(at, &mut salt)?;
            let (key, iv) = crypto.rar4(&salt);
            let mut lead = [0u8; 16];
            read(at + 8, &mut lead)?;
            crypto.decrypt(&key, &iv, &mut lead);
            let size = u64::from(u16::from_le_bytes([lead[5], lead[6]]));
            let total = align16(size);
            if size < 7 || at + 8 + total > length {
                return Err(EngineError::Unsupported(
                    "RAR4 encrypted header does not decrypt (wrong password?)",
                ));
            }
            let mut header = vec![0; total as usize];
            read(at + 8, &mut header)?;
            crypto.decrypt(&key, &iv, &mut header);
            header.truncate(size as usize);
            (header, 8 + total)
        }
    };
    let (bytes, disk) = header;
    let stored = u16::from_le_bytes([bytes[0], bytes[1]]);
    if (crc32(&bytes[2..]) & 0xffff) as u16 != stored {
        return Err(EngineError::Unsupported("RAR4 header CRC mismatch"));
    }
    Ok((bytes, disk))
}

/// Name, salt offset and data length of a RAR4 file or `NEWSUB` header.
fn rar4_file_fields(header: &[u8]) -> EngineResult<(&[u8], usize, u64, u64)> {
    let flags = u16_at(header, 3)?;
    let pack = u64::from(u32_at(header, 7)?);
    let unpacked = u64::from(u32_at(header, 11)?);
    let name_size = usize::from(u16_at(header, 26)?);
    let (mut at, pack, unpacked) = if flags & LHD_LARGE != 0 {
        let high_pack = u64::from(u32_at(header, 32)?);
        let high_unp = u64::from(u32_at(header, 36)?);
        (40, pack | high_pack << 32, unpacked | high_unp << 32)
    } else {
        (32, pack, unpacked)
    };
    let name = header
        .get(at..at + name_size)
        .ok_or(EngineError::Unsupported("truncated RAR4 name"))?;
    at += name_size;
    Ok((name, at, pack, unpacked))
}

fn carrier_magic(
    read: &ReadFn<'_>,
    crypto: Option<&Crypto>,
    at: u64,
    length: u64,
    key: Option<&CarrierKey>,
) -> EngineResult<bool> {
    if length < 16 && key.is_some() || length < 8 {
        return Ok(false);
    }
    let mut lead = [0u8; 16];
    let take = if key.is_some() { 16 } else { 8 };
    read(at, &mut lead[..take])?;
    if let (Some(key), Some(crypto)) = (key, crypto) {
        crypto.decrypt(&key.key, &key.iv, &mut lead);
    }
    Ok(lead[..8] == MAGIC)
}

/// Walk a host. With encrypted headers and no `crypto`, the frame is
/// `opaque` and the whole file counts as the archive.
pub fn inspect(
    access: &dyn SourceAccess,
    source: SourceId,
    options: &ExecutionOptions,
    crypto: Option<&Crypto>,
) -> EngineResult<Frame> {
    let snapshot = access.snapshot(source)?.ok_or(EngineError::Unavailable {
        source_id: source,
        offset: 0,
    })?;
    let length = snapshot.len;
    let read = |offset: u64, out: &mut [u8]| -> EngineResult<()> {
        read_exact_at(&options.diagnostics, access, source, offset, out)
    };
    let (format, signature) = find_signature(&read, length)?;
    let mut frame = Frame {
        format,
        signature,
        is_volume: false,
        first_volume: false,
        volume: None,
        more_volumes: false,
        locked: false,
        encrypted_headers: false,
        opaque: false,
        end_header: None,
        data_crc: None,
        archive_end: length,
        region: None,
        blocks: 0,
        length,
        walk: Vec::new(),
        rar5_key: None,
    };
    match format {
        Format::Rar4 => walk4(&read, crypto, &mut frame)?,
        Format::Rar5 => walk5(&read, crypto, &mut frame)?,
    }
    if frame.opaque {
        return Ok(frame);
    }
    // Zero padding may follow a RAR5 end header of a non-final volume.
    let mut pad = frame.archive_end;
    if format == Format::Rar5 && frame.end_header.is_some() {
        let mut window = [0u8; 4096];
        while pad < length {
            let take = (length - pad).min(window.len() as u64) as usize;
            read(pad, &mut window[..take])?;
            match window[..take].iter().position(|byte| *byte != 0) {
                Some(first) => {
                    pad += first as u64;
                    break;
                }
                None => pad += take as u64,
            }
        }
        frame.archive_end = pad;
    }
    if frame.archive_end < length {
        let at = frame.archive_end;
        if !carrier_magic(&read, None, at, length - at, None)? {
            return Err(EngineError::Unsupported("unknown data after the archive"));
        }
        set_region(
            &mut frame,
            Region {
                layout: Layout::Trailing,
                range: at..length,
                carrier_at: at,
                carrier_len: length - at,
                encrypted: false,
                key: None,
            },
        )?;
    }
    Ok(frame)
}

fn set_region(frame: &mut Frame, region: Region) -> EngineResult<()> {
    if frame.region.is_some() {
        return Err(EngineError::Unsupported("more than one PAR3 region"));
    }
    frame.region = Some(region);
    Ok(())
}

fn walk4(read: &ReadFn<'_>, crypto: Option<&Crypto>, frame: &mut Frame) -> EngineResult<()> {
    let length = frame.length;
    let mut at = frame.signature + SIG4.len() as u64;
    let mut encrypted = false;
    loop {
        if at >= length {
            frame.archive_end = at.min(length);
            return Ok(());
        }
        // Packets at a block boundary: a trailing region of an archive with
        // no end block.
        if carrier_magic(read, None, at, length - at, None)? {
            frame.archive_end = at;
            return Ok(());
        }
        let walker = if encrypted { crypto } else { None };
        let (header, disk) = rar4_header_at(read, at, length, walker)?;
        frame.blocks += 1;
        let kind = header[2];
        let flags = u16_at(&header, 3)?;
        let mut data = if flags & LONG_BLOCK != 0 {
            u64::from(u32_at(&header, 7)?)
        } else {
            0
        };
        if (kind == FILE4 || kind == NEWSUB) && flags & LHD_LARGE != 0 {
            data |= u64::from(u32_at(&header, 32)?) << 32;
        }
        let data_at = at + disk;
        let block_end = data_at
            .checked_add(data)
            .filter(|end| *end <= length)
            .ok_or(EngineError::Unsupported("truncated RAR4 data area"))?;
        let mut label = format!("{kind:#04x} flags={flags:#06x} head={disk} data={data}");
        match kind {
            MAIN4 => {
                frame.is_volume = flags & MHD_VOLUME != 0;
                frame.locked = flags & MHD_LOCK != 0;
                frame.first_volume = flags & MHD_FIRSTVOLUME != 0;
                if flags & MHD_PASSWORD != 0 {
                    frame.encrypted_headers = true;
                    encrypted = true;
                    if crypto.is_none() {
                        frame.opaque = true;
                        frame.walk.push((at, label));
                        return Ok(());
                    }
                }
            }
            NEWSUB | FILE4 => {
                let (name, salt_at, _pack, unpacked) = rar4_file_fields(&header)?;
                label.push_str(&format!(
                    " name={:?}",
                    String::from_utf8_lossy(&name[..name.len().min(48)])
                ));
                if kind == NEWSUB && name == SERVICE_NAME {
                    let encrypted_data = flags & LHD_PASSWORD != 0;
                    let (key, carrier_len) = if encrypted_data {
                        let crypto = crypto.ok_or(EngineError::Unsupported(
                            "encrypted PAR3 block needs the password",
                        ))?;
                        let salt: [u8; 8] = header
                            .get(salt_at..salt_at + 8)
                            .ok_or(EngineError::Unsupported("truncated RAR4 salt"))?
                            .try_into()
                            .expect("salt");
                        let (key, iv) = crypto.rar4(&salt);
                        (
                            Some(CarrierKey {
                                key: key.to_vec(),
                                iv,
                            }),
                            unpacked,
                        )
                    } else {
                        (None, data.saturating_sub(8))
                    };
                    if carrier_magic(read, crypto, data_at, data, key.as_ref())? {
                        set_region(
                            frame,
                            Region {
                                layout: Layout::Service,
                                range: at..block_end,
                                carrier_at: data_at,
                                carrier_len,
                                encrypted: encrypted_data,
                                key,
                            },
                        )?;
                    }
                }
            }
            ENDARC => {
                frame.more_volumes = flags & EARC_NEXT_VOLUME != 0;
                let mut field = 7;
                if flags & EARC_DATACRC != 0 {
                    frame.data_crc = Some(u32_at(&header, field)?);
                    field += 4;
                }
                if flags & EARC_VOLNUMBER != 0 {
                    frame.volume = Some(u64::from(u16_at(&header, field)?));
                }
                frame.end_header = Some(at..at + disk);
                frame.archive_end = at + disk;
                frame.walk.push((at, label));
                return Ok(());
            }
            _ => {}
        }
        frame.walk.push((at, label));
        at = block_end;
    }
}

/// Read one RAR5 header at `at`: plain header bytes, length on disk and the
/// offset of the first field.
fn rar5_header_at(
    read: &ReadFn<'_>,
    at: u64,
    length: u64,
    key: Option<(&Crypto, &[u8; 32])>,
) -> EngineResult<(Vec<u8>, u64, usize)> {
    let truncated = EngineError::Unsupported("truncated RAR5 header");
    let (header, disk, cursor) = match key {
        None => {
            let avail = (length.saturating_sub(at)).min(7) as usize;
            if avail < 5 {
                return Err(truncated);
            }
            let mut lead = [0u8; 7];
            read(at, &mut lead[..avail])?;
            let mut cursor = 4;
            let size = read_vint(&lead[..avail], &mut cursor)?;
            if size == 0 || size > 2 << 20 || at + cursor as u64 + size > length {
                return Err(truncated);
            }
            let total = cursor as u64 + size;
            let mut header = vec![0; total as usize];
            read(at, &mut header)?;
            (header, total, cursor)
        }
        Some((crypto, key)) => {
            if length.saturating_sub(at) < 32 {
                return Err(truncated);
            }
            let mut iv = [0u8; 16];
            read(at, &mut iv)?;
            let mut lead = [0u8; 16];
            read(at + 16, &mut lead)?;
            crypto.decrypt(key, &iv, &mut lead);
            let mut cursor = 4;
            let size = read_vint(&lead, &mut cursor)?;
            let plain = cursor as u64 + size;
            let total = align16(plain);
            if size == 0 || size > 2 << 20 || at + 16 + total > length {
                return Err(EngineError::Unsupported(
                    "RAR5 encrypted header does not decrypt (wrong password?)",
                ));
            }
            let mut header = vec![0; total as usize];
            read(at + 16, &mut header)?;
            crypto.decrypt(key, &iv, &mut header);
            header.truncate(plain as usize);
            (header, 16 + total, cursor)
        }
    };
    if crc32(&header[4..]) != u32::from_le_bytes(header[..4].try_into().expect("crc")) {
        return Err(EngineError::Unsupported("RAR5 header CRC mismatch"));
    }
    Ok((header, disk, cursor))
}

/// The RAR5 encryption header fields after the common ones.
fn rar5_crypt_fields(header: &[u8], mut field: usize) -> EngineResult<([u8; 16], u8)> {
    read_vint(header, &mut field)?; // version
    read_vint(header, &mut field)?; // flags
    let lg2 = *header
        .get(field)
        .ok_or(EngineError::Unsupported("truncated RAR5 encryption header"))?;
    let salt: [u8; 16] = header
        .get(field + 1..field + 17)
        .ok_or(EngineError::Unsupported("truncated RAR5 encryption header"))?
        .try_into()
        .expect("salt");
    Ok((salt, lg2))
}

fn walk5(read: &ReadFn<'_>, crypto: Option<&Crypto>, frame: &mut Frame) -> EngineResult<()> {
    let length = frame.length;
    let mut at = frame.signature + SIG5.len() as u64;
    let mut header_key: Option<[u8; 32]> = None;
    loop {
        if at >= length {
            frame.archive_end = at.min(length);
            return Ok(());
        }
        if carrier_magic(read, None, at, length - at, None)? {
            frame.archive_end = at;
            return Ok(());
        }
        let key = match (header_key.as_ref(), crypto) {
            (Some(key), Some(crypto)) => Some((crypto, key)),
            _ => None,
        };
        let (header, disk, cursor) = rar5_header_at(read, at, length, key)?;
        frame.blocks += 1;
        let mut field = cursor;
        let kind = read_vint(&header, &mut field)?;
        let flags = read_vint(&header, &mut field)?;
        let extra = if flags & 0x1 != 0 {
            read_vint(&header, &mut field)?
        } else {
            0
        };
        let data = if flags & 0x2 != 0 {
            read_vint(&header, &mut field)?
        } else {
            0
        };
        let data_at = at + disk;
        let block_end = data_at
            .checked_add(data)
            .filter(|end| *end <= length)
            .ok_or(EngineError::Unsupported("truncated RAR5 data area"))?;
        let mut label = format!("type {kind} flags={flags:#x} head={disk} data={data}");
        match kind {
            1 => {
                let archive_flags = read_vint(&header, &mut field)?;
                frame.is_volume = archive_flags & 0x1 != 0;
                if frame.is_volume {
                    frame.volume = Some(if archive_flags & 0x2 != 0 {
                        read_vint(&header, &mut field)?
                    } else {
                        0
                    });
                }
                frame.locked = archive_flags & 0x10 != 0;
            }
            4 => {
                frame.encrypted_headers = true;
                let (salt, lg2) = rar5_crypt_fields(&header, field)?;
                match crypto {
                    None => {
                        frame.opaque = true;
                        frame.walk.push((at, label));
                        return Ok(());
                    }
                    Some(crypto) => {
                        let key = crypto.rar5(&salt, lg2);
                        header_key = Some(key);
                        frame.rar5_key = Some((key, salt, lg2));
                    }
                }
            }
            5 => {
                let end_flags = read_vint(&header, &mut field)?;
                frame.more_volumes = end_flags & 0x1 != 0;
                frame.end_header = Some(at..at + disk);
                frame.archive_end = at + disk;
                frame.walk.push((at, label));
                return Ok(());
            }
            3 => {
                let (name, unpacked) = rar5_service_name(&header, field)?;
                label.push_str(&format!(" name={:?}", String::from_utf8_lossy(name)));
                if name == SERVICE_NAME {
                    let crypt = rar5_extra_crypt(&header, extra)?;
                    let key = match (crypt, crypto) {
                        (Some((salt, lg2, iv)), Some(crypto)) => Some(CarrierKey {
                            key: crypto.rar5(&salt, lg2).to_vec(),
                            iv,
                        }),
                        (Some(_), None) => {
                            return Err(EngineError::Unsupported(
                                "encrypted PAR3 service needs the password",
                            ));
                        }
                        (None, _) => None,
                    };
                    let carrier_len = if key.is_some() { unpacked } else { data };
                    if carrier_magic(read, crypto, data_at, data, key.as_ref())? {
                        let encrypted = key.is_some();
                        set_region(
                            frame,
                            Region {
                                layout: Layout::Service,
                                range: at..block_end,
                                carrier_at: data_at,
                                carrier_len,
                                encrypted,
                                key,
                            },
                        )?;
                    }
                }
            }
            _ => {}
        }
        frame.walk.push((at, label));
        at = block_end;
    }
}

fn rar5_service_name(header: &[u8], mut field: usize) -> EngineResult<(&[u8], u64)> {
    let flags = read_vint(header, &mut field)?;
    let unpacked = read_vint(header, &mut field)?;
    read_vint(header, &mut field)?;
    if flags & 0x2 != 0 {
        field += 4;
    }
    if flags & 0x4 != 0 {
        field += 4;
    }
    read_vint(header, &mut field)?;
    read_vint(header, &mut field)?;
    let length = read_vint(header, &mut field)? as usize;
    let name = header
        .get(field..field.saturating_add(length))
        .ok_or(EngineError::Unsupported("truncated RAR5 name"))?;
    Ok((name, unpacked))
}

/// The file-encryption record of a RAR5 header's extra area, if any.
fn rar5_extra_crypt(header: &[u8], extra: u64) -> EngineResult<Option<Rar5CryptRecord>> {
    if extra == 0 {
        return Ok(None);
    }
    let start = header
        .len()
        .checked_sub(extra as usize)
        .ok_or(EngineError::Unsupported("RAR5 extra area size"))?;
    let mut at = start;
    while at < header.len() {
        let size = read_vint(header, &mut at)? as usize;
        let record_end = at + size;
        let mut field = at;
        let kind = read_vint(header, &mut field)?;
        if kind == 1 {
            read_vint(header, &mut field)?;
            read_vint(header, &mut field)?;
            let lg2 = *header
                .get(field)
                .ok_or(EngineError::Unsupported("truncated crypt record"))?;
            let salt: [u8; 16] = header
                .get(field + 1..field + 17)
                .ok_or(EngineError::Unsupported("truncated crypt record"))?
                .try_into()
                .expect("salt");
            let iv: [u8; 16] = header
                .get(field + 17..field + 33)
                .ok_or(EngineError::Unsupported("truncated crypt record"))?
                .try_into()
                .expect("iv");
            return Ok(Some((salt, lg2, iv)));
        }
        at = record_end;
    }
    Ok(None)
}

/// Rendering context of a host from its own (possibly restored) bytes.
fn host_ctx(
    access: &dyn SourceAccess,
    source: SourceId,
    spec: Spec,
    end_at: u64,
    length: u64,
    options: &ExecutionOptions,
    crypto: Option<&Crypto>,
) -> EngineResult<HostCtx> {
    let read = |offset: u64, out: &mut [u8]| -> EngineResult<()> {
        read_exact_at(&options.diagnostics, access, source, offset, out)
    };
    let mut ctx = HostCtx::default();
    if spec.layout != Layout::Service {
        return Ok(ctx);
    }
    match spec.format {
        Format::Rar4 => {
            if end_at < length {
                let walker = if spec.encrypted { crypto } else { None };
                let (header, _) = rar4_header_at(&read, end_at, length, walker)?;
                let flags = u16_at(&header, 3)?;
                if header[2] == ENDARC && flags & EARC_DATACRC != 0 {
                    ctx.data_crc = Some(u32_at(&header, 7)?);
                }
            }
        }
        Format::Rar5 => {
            if spec.encrypted {
                let crypto = crypto.ok_or(EngineError::Unsupported(
                    "encrypted headers need the password",
                ))?;
                let (_, signature) = find_signature(&read, length)?;
                let (header, _, cursor) =
                    rar5_header_at(&read, signature + SIG5.len() as u64, length, None)?;
                let mut field = cursor;
                if read_vint(&header, &mut field)? != 4 {
                    return Err(EngineError::Unsupported("RAR5 encryption header not found"));
                }
                read_vint(&header, &mut field)?;
                let (salt, lg2) = rar5_crypt_fields(&header, field)?;
                ctx.rar5_key = Some((crypto.rar5(&salt, lg2), salt, lg2));
            }
        }
    }
    Ok(ctx)
}

/// The raw CRC32 register over `range` of a source.
fn crc_register(
    access: &dyn SourceAccess,
    source: SourceId,
    range: Range<u64>,
    options: &ExecutionOptions,
) -> EngineResult<u32> {
    let mut digest = Digest::new(CrcAlgorithm::Crc32IsoHdlc);
    let mut buffer = vec![0u8; 1 << 16];
    let mut at = range.start;
    while at < range.end {
        let take = (range.end - at).min(buffer.len() as u64) as usize;
        read_exact_at(
            &options.diagnostics,
            access,
            source,
            at,
            &mut buffer[..take],
        )?;
        digest.update(&buffer[..take]);
        at += take as u64;
    }
    Ok(!(digest.finalize() as u32))
}

/// A view of hosts with each encrypted carrier shown as plain bytes at the
/// same offsets.
struct PlainView {
    raw: Arc<dyn SourceAccess>,
    carriers: HashMap<SourceId, (u64, u64, CarrierKey)>,
    crypto: Option<Arc<Crypto>>,
}

impl SourceAccess for PlainView {
    fn snapshot(&self, source: SourceId) -> io::Result<Option<SourceSnapshot>> {
        self.raw.snapshot(source)
    }

    fn read_at(&self, source: SourceId, offset: u64, output: &mut [u8]) -> io::Result<usize> {
        let Some((start, len, key)) = self.carriers.get(&source) else {
            return self.raw.read_at(source, offset, output);
        };
        let end = start + len;
        if offset < *start {
            let take = (start - offset).min(output.len() as u64) as usize;
            return self.raw.read_at(source, offset, &mut output[..take]);
        }
        if offset >= end {
            return self.raw.read_at(source, offset, output);
        }
        let crypto = self.crypto.as_ref().expect("crypto for encrypted carrier");
        let take = (end - offset).min(output.len() as u64);
        let relative = offset - start;
        let block_start = relative / 16 * 16;
        let block_end = align16(relative + take);
        let previous = if block_start == 0 { 0 } else { 16 };
        let mut cipher = vec![0u8; (block_end - block_start + previous) as usize];
        let mut at = 0usize;
        while at < cipher.len() {
            let read = self.raw.read_at(
                source,
                start + block_start - previous + at as u64,
                &mut cipher[at..],
            )?;
            if read == 0 {
                return Err(io::Error::new(
                    io::ErrorKind::UnexpectedEof,
                    "short carrier",
                ));
            }
            at += read;
        }
        let iv: [u8; 16] = if block_start == 0 {
            key.iv
        } else {
            cipher[..16].try_into().expect("block")
        };
        let blocks = &mut cipher[previous as usize..];
        crypto.decrypt(&key.key, &iv, blocks);
        let skip = (relative - block_start) as usize;
        output[..take as usize].copy_from_slice(&blocks[skip..skip + take as usize]);
        Ok(take as usize)
    }

    fn next_available(&self, source: SourceId, offset: u64) -> io::Result<Option<Range<u64>>> {
        self.raw.next_available(source, offset)
    }
}

/// One host prepared for insertion.
#[derive(Clone, Debug)]
pub struct Host {
    /// Existing host file.
    pub path: PathBuf,
    /// Name recorded in the File packet.
    pub name: String,
    /// Framing of the host.
    pub frame: Frame,
    snapshot: SourceSnapshot,
}

/// Bytes added to one host.
#[derive(Clone, Debug)]
pub struct Inserted {
    /// Output written.
    pub path: PathBuf,
    /// Region bytes.
    pub region_bytes: u64,
    /// Recovery Data packets in the region.
    pub recovery_packets: u64,
    /// Input set.
    pub set: InputSetId,
}

/// Inspect hosts for insertion.
pub fn prepare_hosts(
    paths: &[PathBuf],
    layout: Layout,
    options: &ExecutionOptions,
    crypto: Option<&Crypto>,
) -> EngineResult<(Spec, Vec<Host>)> {
    if paths.is_empty() {
        return Err(EngineError::InvalidState("insert host count"));
    }
    let disk: Arc<dyn SourceAccess> = Arc::new(disk_access(paths, options));
    let mut hosts = Vec::new();
    for (index, path) in paths.iter().enumerate() {
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or(EngineError::Unsupported("host name is not UTF-8"))?
            .to_owned();
        r5::validate_host_name(&name)?;
        let source = SourceId(index as u64);
        let snapshot = disk.snapshot(source)?.ok_or(EngineError::Unavailable {
            source_id: source,
            offset: 0,
        })?;
        let frame = inspect(disk.as_ref(), source, options, crypto)?;
        if frame.region.is_some() {
            return Err(EngineError::Unsupported(
                "archive already holds a PAR3 region",
            ));
        }
        if frame.opaque && layout == Layout::Service {
            return Err(EngineError::Unsupported(
                "encrypted headers need the password for the service layout",
            ));
        }
        hosts.push(Host {
            path: path.clone(),
            name,
            frame,
            snapshot,
        });
    }
    let format = hosts[0].frame.format;
    let encrypted = hosts[0].frame.encrypted_headers;
    if hosts
        .iter()
        .any(|host| host.frame.format != format || host.frame.encrypted_headers != encrypted)
    {
        return Err(EngineError::Unsupported(
            "hosts differ in format or encryption",
        ));
    }
    let names: BTreeSet<_> = hosts.iter().map(|host| host.name.as_str()).collect();
    if names.len() != hosts.len() {
        return Err(EngineError::Unsupported("duplicate host names"));
    }
    Ok((
        Spec {
            format,
            layout,
            encrypted: encrypted && layout == Layout::Service,
        },
        hosts,
    ))
}

/// Insert one set over `hosts`; host `k` with its region goes to the absent
/// `outputs[k]` and carries `counts[k]` recovery packets.
#[allow(clippy::too_many_arguments)]
pub fn insert_set(
    hosts: &[Host],
    outputs: &[PathBuf],
    counts: &[u64],
    spec: Spec,
    options: CreationOptions,
    scratch_directory: &Path,
    crypto: Option<&Crypto>,
) -> EngineResult<Vec<Inserted>> {
    if options.codec != CreationCodec::Cauchy || options.store_data || options.first_recovery != 0 {
        return Err(EngineError::Unsupported(
            "PAR-inside requires Cauchy recovery without Data packets from index zero",
        ));
    }
    if hosts.len() != outputs.len() || hosts.len() != counts.len() || hosts.is_empty() {
        return Err(EngineError::InvalidState("insert host count"));
    }
    let execution = options.execution.clone();
    let paths: Vec<PathBuf> = hosts.iter().map(|host| host.path.clone()).collect();
    let disk: Arc<dyn SourceAccess> = Arc::new(disk_access(&paths, &execution));
    let mut views = BTreeMap::new();
    let mut sources = Vec::new();
    let mut tails = Vec::new();
    let mut splits = Vec::new();
    for (index, host) in hosts.iter().enumerate() {
        let source = SourceId(index as u64);
        let snapshot = disk.snapshot(source)?.ok_or(EngineError::Unavailable {
            source_id: source,
            offset: 0,
        })?;
        if snapshot != host.snapshot {
            return Err(EngineError::Unsupported(
                "host changed since it was inspected",
            ));
        }
        let split = match spec.layout {
            Layout::Trailing => host.frame.archive_end,
            Layout::Service => host.frame.service_at(),
        };
        let body = SourceId(2 * index as u64);
        views.insert(body, (source, snapshot, 0..split));
        sources.push(CreationSource {
            name: host.name.clone(),
            source: body,
        });
        let tail = split < snapshot.len;
        if tail {
            let id = SourceId(2 * index as u64 + 1);
            views.insert(id, (source, snapshot, split..snapshot.len));
            sources.push(CreationSource {
                name: format!(".rar-tail-{index}"),
                source: id,
            });
        }
        tails.push(tail);
        splits.push((split, snapshot));
    }
    let views: Arc<dyn SourceAccess> = Arc::new(HostViews {
        access: disk.clone(),
        views,
    });
    let mut plan = CreationPlan::build_in_source_order(views, &sources, options)?;
    let prefix = move |carrier: u64| spec.prefix(carrier) + spec.suffix(carrier);
    let gaps = plan.embedded_set_layout(&tails, counts, &prefix)?;
    for output in outputs {
        if std::fs::symlink_metadata(output).is_ok() {
            return Err(io::Error::new(io::ErrorKind::AlreadyExists, "PAR3 output exists").into());
        }
    }
    let id = plan.input_set_id();
    let fingerprints = plan.embedded_fingerprints();
    let mut writers: Vec<AuthenticatingWriter<'_, Vec<u8>>> = (0..hosts.len())
        .map(|_| AuthenticatingWriter::new(Vec::new(), id, execution.clone()))
        .collect();
    plan.write_embedded_set(
        &mut writers,
        scratch_directory,
        |_, _| Ok(()),
        |index, writer| {
            writer.flush()?;
            writer.finish(gaps[index].1)?;
            Ok(())
        },
    )?;
    let carriers: Vec<Vec<u8>> = writers.into_iter().map(|w| w.into_inner()).collect();
    let size = execution.stripe_bytes.min(64 << 10);
    let mut buffer = vec![0; size];
    let mut staged: Vec<PathBuf> = Vec::new();
    let result = (|| -> EngineResult<Vec<Inserted>> {
        let mut reports = Vec::new();
        for (index, output) in outputs.iter().enumerate() {
            let (split, snapshot) = splits[index];
            let source = SourceId(index as u64);
            let ctx = host_ctx(
                disk.as_ref(),
                source,
                spec,
                split,
                snapshot.len,
                &execution,
                crypto,
            )?;
            let body = crc_register(disk.as_ref(), source, 0..split, &execution)?;
            let region = render(spec, crypto, id, index, &ctx, body, &carriers[index])?;
            if region.len() as u64 != gaps[index].0 + gaps[index].1 {
                return Err(EngineError::InvalidState(
                    "region length differs from the plan",
                ));
            }
            let (mut file, cloned) = stage(disk.as_ref(), source, output, &execution, &mut staged)?;
            let mut hash = FingerprintHasher::new();
            if cloned {
                file.set_len(split)?;
                io::Seek::seek(&mut file, io::SeekFrom::Start(split))?;
                // The clone shares the body; hash it from the source.
                let mut at = 0;
                while at < split {
                    let take = (split - at).min(size as u64) as usize;
                    read_exact_at(
                        &execution.diagnostics,
                        disk.as_ref(),
                        source,
                        at,
                        &mut buffer[..take],
                    )?;
                    hash.update(&buffer[..take]);
                    at += take as u64;
                }
            } else {
                copy(
                    disk.as_ref(),
                    source,
                    0..split,
                    &mut file,
                    &mut buffer,
                    Some(&mut hash),
                    &execution,
                )?;
            }
            file.write_all(&region)?;
            copy(
                disk.as_ref(),
                source,
                split..snapshot.len,
                &mut file,
                &mut buffer,
                Some(&mut hash),
                &execution,
            )?;
            crate::source::ensure_snapshot(disk.as_ref(), source, snapshot)?;
            if hash.finalize() != fingerprints[index] {
                return Err(EngineError::InvalidState(
                    "embedded output failed verification",
                ));
            }
            file.flush()?;
            drop(file);
            reports.push(Inserted {
                path: output.clone(),
                region_bytes: region.len() as u64,
                recovery_packets: counts[index],
                set: id,
            });
        }
        link_all(&staged, outputs)?;
        Ok(reports)
    })();
    for path in staged {
        let _ = std::fs::remove_file(path);
    }
    result
}

/// One host of an opened set.
#[derive(Clone, Debug)]
pub struct HostState {
    /// Name recorded in the File packet.
    pub name: String,
    /// File bound to this host.
    pub path: Option<PathBuf>,
    /// How the file was matched.
    pub matched_by: Option<&'static str>,
    file: usize,
    source: Option<SourceId>,
    /// The unprotected chunk holding the region.
    pub gap: Range<u64>,
    /// Region bytes before the carrier.
    pub prefix: u64,
    /// Carrier bytes.
    pub carrier: u64,
    /// Expected file length.
    pub length: u64,
    /// Recovery indices carried.
    pub recovery: Range<u64>,
    /// Protected bytes verified.
    pub complete: bool,
    /// Damaged or missing protected ranges.
    pub unresolved: Vec<Range<u64>>,
    /// Region packets found at their exact offsets.
    pub packets_found: u64,
    /// Region packets the layout calls for.
    pub packets_expected: u64,
    /// The region is byte-exact.
    pub region_intact: bool,
}

/// One opened set.
pub struct Set {
    /// Input set.
    pub id: InputSetId,
    /// Region shape.
    pub spec: Spec,
    /// Hosts in set order.
    pub hosts: Vec<HostState>,
    /// Readiness.
    pub status: RepairStatus,
    /// Lost protected blocks.
    pub lost_blocks: u64,
    /// Additional recovery blocks needed.
    pub additional: u64,
    /// Recovery packets usable now.
    pub recovery_available: u64,
    session: Par3RepairSession,
    metadata: Vec<Vec<u8>>,
    raw: Arc<dyn SourceAccess>,
    crypto: Option<Arc<Crypto>>,
}

struct Discovery {
    candidates: Vec<Candidate>,
    frames: HashMap<SourceId, Frame>,
    view: Arc<dyn SourceAccess>,
    raw: Arc<dyn SourceAccess>,
}

fn discover(
    known: &[PathBuf],
    options: &ExecutionOptions,
    crypto: &Option<Arc<Crypto>>,
) -> EngineResult<Discovery> {
    let raw: Arc<dyn SourceAccess> = Arc::new(disk_access(known, options));
    let mut frames = HashMap::new();
    let mut carriers = HashMap::new();
    for (index, path) in known.iter().enumerate() {
        if !path.is_file() {
            continue;
        }
        let source = SourceId(index as u64);
        if let Ok(frame) = inspect(raw.as_ref(), source, options, crypto.as_deref()) {
            if let Some(region) = &frame.region
                && let Some(key) = &region.key
            {
                carriers.insert(source, (region.carrier_at, region.carrier_len, key.clone()));
            }
            frames.insert(source, frame);
        }
    }
    let view: Arc<dyn SourceAccess> = Arc::new(PlainView {
        raw: raw.clone(),
        carriers,
        crypto: crypto.clone(),
    });
    let mut candidates = Vec::new();
    for (index, path) in known.iter().enumerate() {
        if !path.is_file() {
            continue;
        }
        let source = SourceId(index as u64);
        let frame = frames.get(&source);
        let from = frame
            .and_then(|frame| frame.region.as_ref().map(|region| region.range.start))
            .unwrap_or(0);
        let mut packets: Vec<IngestedPacket> = scan(view.clone(), source, from, options)?;
        if packets.is_empty() && from != 0 {
            packets = scan(view.clone(), source, 0, options)?;
        }
        candidates.push(Candidate::new(
            path.clone(),
            source,
            frame.and_then(|frame| frame.volume),
            packets,
        ));
    }
    Ok(Discovery {
        candidates,
        frames,
        view,
        raw,
    })
}

/// Open every set found in `paths`; hosts recorded in a set but absent are
/// looked up beside the given files under their recorded names.
pub fn open(
    paths: &[PathBuf],
    options: &ExecutionOptions,
    crypto: Option<Arc<Crypto>>,
) -> EngineResult<Vec<Set>> {
    let mut known: Vec<PathBuf> = Vec::new();
    let mut seen: HashSet<PathBuf> = HashSet::new();
    for path in paths {
        if seen.insert(path.clone()) {
            known.push(path.clone());
        }
    }
    let first = discover(&known, options, &crypto)?;
    let mut names = BTreeSet::new();
    {
        let mut sessions: BTreeMap<InputSetId, Par3RepairSession> = BTreeMap::new();
        for candidate in &first.candidates {
            for packet in candidate.packets.iter().filter(|p| p.metadata().is_some()) {
                let id = packet.input_set_id();
                if let std::collections::btree_map::Entry::Vacant(entry) = sessions.entry(id) {
                    entry.insert(Par3RepairSession::new(
                        id,
                        first.view.clone(),
                        options.clone(),
                    )?);
                }
                sessions
                    .get_mut(&id)
                    .expect("session")
                    .merge(packet.clone())?;
            }
        }
        for mut session in sessions.into_values() {
            if let Some(layout) = session.layout()? {
                for file in layout.files() {
                    names.insert(file.path.clone());
                }
            }
        }
    }
    drop(first);
    let directories: Vec<PathBuf> = known
        .iter()
        .filter_map(|path| path.parent().map(Path::to_path_buf))
        .collect();
    for name in names {
        if r5::validate_host_name(&name).is_err() {
            continue;
        }
        for directory in &directories {
            let path = directory.join(&name);
            if !seen.contains(&path) && path.is_file() {
                seen.insert(path.clone());
                known.push(path);
            }
        }
    }
    let found = discover(&known, options, &crypto)?;
    let mut ids: Vec<InputSetId> = Vec::new();
    let mut listed = HashSet::new();
    for candidate in &found.candidates {
        for packet in &candidate.packets {
            if listed.insert(packet.input_set_id()) {
                ids.push(packet.input_set_id());
            }
        }
    }
    if ids.is_empty() {
        return Err(EngineError::Unsupported("no PAR3 packets found"));
    }
    ids.into_iter()
        .map(|id| open_set(id, &found, options, crypto.clone()))
        .collect()
}

fn solve(spec: Spec, gap: u64, metadata: u64, packet: u64) -> Option<(u64, u64, u64)> {
    if packet == 0 {
        return None;
    }
    // The carrier is metadata plus whole recovery packets.
    let mut count = 0u64;
    loop {
        let carrier = metadata.checked_add(packet.checked_mul(count)?)?;
        let total = spec.gap(carrier);
        if total == gap {
            return Some((spec.prefix(carrier), carrier, count));
        }
        if total > gap {
            return None;
        }
        count += 1;
    }
}

fn open_set(
    id: InputSetId,
    found: &Discovery,
    options: &ExecutionOptions,
    crypto: Option<Arc<Crypto>>,
) -> EngineResult<Set> {
    let candidates = &found.candidates;
    let access = found.view.clone();
    let mut session = Par3RepairSession::new(id, access.clone(), options.clone())?;
    for candidate in candidates {
        for packet in candidate.packets_of(id) {
            session.merge(packet.clone())?;
        }
    }
    let layout = session
        .layout()?
        .ok_or(EngineError::Unsupported("PAR3 metadata is incomplete"))?;
    let block_size = session
        .set()
        .ok_or(EngineError::Unsupported("PAR3 metadata is incomplete"))?
        .block_size();
    let metadata_hashes: BTreeSet<Fingerprint> = session
        .input
        .packets()
        .filter_map(|packet| packet.metadata().map(|metadata| metadata.hash()))
        .collect();
    let mut metadata: Option<Vec<Vec<u8>>> = None;
    for candidate in candidates {
        let mut packets: Vec<&IngestedPacket> = candidate.packets_of(id).collect();
        packets.sort_by_key(|packet| packet.origin().offset);
        let mut run = Vec::new();
        let mut seen = BTreeSet::new();
        let mut next = None;
        for packet in packets {
            let origin = packet.origin();
            let Some(metadata) = packet.metadata() else {
                break;
            };
            if next.is_some_and(|next| next != origin.offset) {
                break;
            }
            next = Some(origin.offset + origin.length);
            seen.insert(metadata.hash());
            run.push(metadata.to_bytes());
        }
        if seen == metadata_hashes {
            metadata = Some(run);
            break;
        }
    }
    let metadata = metadata.ok_or(EngineError::Unsupported(
        "no region holds a complete metadata run",
    ))?;
    let metadata_bytes: u64 = metadata.iter().map(|packet| packet.len() as u64).sum();
    let mut by_hash: HashMap<Fingerprint, usize> = HashMap::with_capacity(layout.files().len());
    for (index, file) in layout.files().iter().enumerate() {
        by_hash.entry(file.packet_hash).or_insert(index);
    }
    let mut placed = vec![false; layout.files().len()];
    let mut order = Vec::new();
    for bytes in &metadata {
        let hash: Fingerprint = bytes[8..24].try_into().expect("packet hash");
        if let Some(&file) = by_hash.get(&hash)
            && !std::mem::replace(&mut placed[file], true)
        {
            order.push(file);
        }
    }
    if order.len() != layout.files().len() {
        return Err(EngineError::Unsupported(
            "File packets are not in the metadata run",
        ));
    }
    // Format and encryption come from any host that carries this set.
    let frame = candidates
        .iter()
        .filter(|c| c.carries(id))
        .find_map(|c| found.frames.get(&c.source))
        .ok_or(EngineError::Unsupported(
            "no host of the set could be walked",
        ))?;
    let recovery_len = packet_len(block_size)?;
    let mut spec_found: Option<Spec> = None;
    let mut hosts = Vec::new();
    for &file in &order {
        let entry = &layout.files()[file];
        let mut gaps = (0..entry.extents.len())
            .filter(|index| entry.extents.is_unprotected(*index))
            .filter_map(|index| entry.extents.range(index));
        let gap = gaps
            .next()
            .ok_or(EngineError::Unsupported("host has no region"))?;
        if gaps.next().is_some() {
            return Err(EngineError::Unsupported("host has more than one region"));
        }
        let length = gap.end - gap.start;
        let mut solved = None;
        for candidate in [Layout::Service, Layout::Trailing] {
            if candidate == Layout::Trailing && gap.end != entry.len {
                continue;
            }
            let spec = Spec {
                format: frame.format,
                layout: candidate,
                encrypted: frame.encrypted_headers && candidate == Layout::Service,
            };
            if let Some((prefix, carrier, count)) =
                solve(spec, length, metadata_bytes, recovery_len)
            {
                solved = Some((spec, prefix, carrier, count));
                break;
            }
        }
        let (spec, prefix, carrier, count) =
            solved.ok_or(EngineError::Unsupported("region length fits no layout"))?;
        if spec_found.is_some_and(|found| found != spec) {
            return Err(EngineError::Unsupported(
                "hosts use different region layouts",
            ));
        }
        spec_found = Some(spec);
        hosts.push(HostState {
            name: entry.path.clone(),
            path: None,
            matched_by: None,
            file,
            source: None,
            gap: gap.clone(),
            prefix,
            carrier,
            length: entry.len,
            recovery: 0..count,
            complete: false,
            unresolved: Vec::new(),
            packets_found: 0,
            packets_expected: metadata.len() as u64 + count,
            region_intact: false,
        });
    }
    let spec = spec_found.ok_or(EngineError::Unsupported("set names no host file"))?;
    // Bind files: recorded name, recovery indices, volume number, lone file.
    let mut used = BTreeSet::new();
    for host in &mut hosts {
        if let Some(candidate) = candidates.iter().find(|c| {
            file_name(&c.path) == Some(host.name.as_str())
                && !used.contains(&c.source)
                && (c.carries(id) || !c.carries_other_than(id))
        }) {
            used.insert(candidate.source);
            host.source = Some(candidate.source);
            host.path = Some(candidate.path.clone());
            host.matched_by = Some("name");
        }
    }
    let mut first_index = None;
    'base: for (position, host) in hosts.iter().enumerate() {
        let Some(source) = host.source else { continue };
        let candidate = candidates
            .iter()
            .find(|c| c.source == source)
            .expect("bound");
        let start = host.gap.start + host.prefix + metadata_bytes;
        let before: u64 = hosts[..position].iter().map(|host| host.recovery.end).sum();
        for packet in candidate.packets_of(id) {
            let Some(PayloadKind::Recovery { index, .. }) = packet.payload().map(|p| p.kind())
            else {
                continue;
            };
            let offset = packet.origin().offset;
            if offset >= start && (offset - start).is_multiple_of(recovery_len) {
                let slot = (offset - start) / recovery_len;
                let earlier = before
                    .checked_add(slot)
                    .ok_or(EngineError::Unsupported("recovery index out of range"))?;
                if slot < host.recovery.end && index >= earlier {
                    first_index = Some(index - earlier);
                    break 'base;
                }
            }
        }
    }
    let counts: Vec<u64> = hosts.iter().map(|host| host.recovery.end).collect();
    for (host, range) in hosts
        .iter_mut()
        .zip(recovery_ranges(first_index.unwrap_or(0), &counts)?)
    {
        host.recovery = range;
    }
    for host in hosts.iter_mut().filter(|host| host.source.is_none()) {
        let by_recovery = candidates.iter().find(|c| {
            !used.contains(&c.source)
                && c.packets_of(id).any(|p| {
                    matches!(p.payload().map(|p| p.kind()),
                        Some(PayloadKind::Recovery { index, .. }) if host.recovery.contains(&index))
                })
        });
        if let Some(candidate) = by_recovery {
            used.insert(candidate.source);
            host.source = Some(candidate.source);
            host.path = Some(candidate.path.clone());
            host.matched_by = Some("recovery indices");
        }
    }
    if hosts.len() == 1 && hosts[0].source.is_none() {
        let free: Vec<_> = candidates
            .iter()
            .filter(|c| !used.contains(&c.source) && c.carries(id))
            .collect();
        if let [candidate] = free.as_slice() {
            hosts[0].source = Some(candidate.source);
            hosts[0].path = Some(candidate.path.clone());
            hosts[0].matched_by = Some("only file");
        }
    }
    for host in &hosts {
        if let Some(source) = host.source {
            session.bind_file(&host.name, source)?;
        }
    }
    let assessment = session.assess()?;
    let status = assessment.status;
    let lost_blocks = assessment.lost_blocks.len() as u64;
    let additional = assessment.requirements.iter().map(|r| r.additional).sum();
    let recovery_available = assessment.recovery.len() as u64;
    let files = assessment.files.clone();
    for (index, host) in hosts.iter_mut().enumerate() {
        let assessed = files
            .iter()
            .find(|file| file.path == host.name)
            .ok_or(EngineError::InvalidState("assessed host"))?;
        host.complete = assessed.complete && host.source.is_some();
        host.unresolved = if host.source.is_some() {
            assessed.unresolved.clone()
        } else {
            std::iter::once(0..host.length).collect()
        };
        let Some(source) = host.source else { continue };
        let candidate = candidates
            .iter()
            .find(|c| c.source == source)
            .expect("bound");
        let mut hashes_at = BTreeSet::new();
        let mut recovery_at = BTreeSet::new();
        for p in candidate.packets_of(id) {
            let offset = p.origin().offset;
            hashes_at.insert((offset, p.hash()));
            if let Some(PayloadKind::Recovery { index, .. }) = p.payload().map(|p| p.kind()) {
                recovery_at.insert((offset, index));
            }
        }
        let mut found_packets = 0;
        let mut offset = host.gap.start + host.prefix;
        for bytes in &metadata {
            let hash: Fingerprint = bytes[8..24].try_into().expect("hash");
            if hashes_at.contains(&(offset, hash)) {
                found_packets += 1;
            }
            offset += bytes.len() as u64;
        }
        for recovery in host.recovery.clone() {
            if recovery_at.contains(&(offset, recovery)) {
                found_packets += 1;
            }
            offset += recovery_len;
        }
        host.packets_found = found_packets;
        let snapshot = found.raw.snapshot(source)?;
        let length_ok = snapshot.is_some_and(|snapshot| snapshot.len == host.length);
        host.region_intact = found_packets == host.packets_expected
            && length_ok
            && region_matches(
                spec,
                id,
                index,
                host,
                found.raw.as_ref(),
                access.as_ref(),
                source,
                options,
                crypto.as_deref(),
            )
            .unwrap_or(false);
    }
    Ok(Set {
        id,
        spec,
        hosts,
        status,
        lost_blocks,
        additional,
        recovery_available,
        session,
        metadata,
        raw: found.raw.clone(),
        crypto,
    })
}

/// Whether the region on disk is exactly what rendering its carrier gives.
#[allow(clippy::too_many_arguments)]
fn region_matches(
    spec: Spec,
    id: InputSetId,
    index: usize,
    host: &HostState,
    raw: &dyn SourceAccess,
    view: &dyn SourceAccess,
    source: SourceId,
    options: &ExecutionOptions,
    crypto: Option<&Crypto>,
) -> EngineResult<bool> {
    let mut carrier = vec![0u8; host.carrier as usize];
    read_exact_at(
        &options.diagnostics,
        view,
        source,
        host.gap.start + host.prefix,
        &mut carrier,
    )?;
    let ctx = host_ctx(
        raw,
        source,
        spec,
        host.gap.end,
        host.length,
        options,
        crypto,
    )?;
    let body = crc_register(raw, source, 0..host.gap.start, options)?;
    let expected = render(spec, crypto, id, index, &ctx, body, &carrier)?;
    let mut actual = vec![0u8; expected.len()];
    read_exact_at(
        &options.diagnostics,
        raw,
        source,
        host.gap.start,
        &mut actual,
    )?;
    Ok(actual == expected)
}

/// What self-repair did for one host.
#[derive(Clone, Debug)]
pub struct Repaired {
    /// Recorded host name.
    pub name: String,
    /// Output written.
    pub path: PathBuf,
    /// Protected bytes were rebuilt.
    pub data_rebuilt: bool,
    /// Recovery packets regenerated.
    pub regenerated: usize,
    /// Whether the carrier is the authenticated original.
    pub restoration: CarrierRestoration,
}

impl Set {
    /// Hosts whose protected bytes or region are not intact.
    pub fn needs_repair(&self) -> Vec<usize> {
        (0..self.hosts.len())
            .filter(|&index| !self.hosts[index].complete || !self.hosts[index].region_intact)
            .collect()
    }

    /// Rebuild every host that needs it to `destinations[k]` (absent).
    pub fn repair(
        &mut self,
        destinations: &[PathBuf],
        scratch_directory: &Path,
    ) -> EngineResult<Vec<Repaired>> {
        if destinations.len() != self.hosts.len() {
            return Err(EngineError::InvalidState("repair destination count"));
        }
        let needed = self.needs_repair();
        if needed.is_empty() {
            return Ok(Vec::new());
        }
        if !matches!(self.status, RepairStatus::Ready | RepairStatus::Complete) {
            return Err(EngineError::Unsupported(
                "not enough recovery data to repair",
            ));
        }
        for &index in &needed {
            if std::fs::symlink_metadata(&destinations[index]).is_ok() {
                return Err(
                    io::Error::new(io::ErrorKind::AlreadyExists, "repair output exists").into(),
                );
            }
        }
        let options = self.session.options.clone();
        let layout = self.session.layout()?.expect("layout");
        let mut scratch = Vec::new();
        for host in 0..layout.files().len() {
            scratch.push(crate::session_repair::ScratchFile::new(
                &scratch_directory.join(format!("host-{host}")),
                &options,
            )?);
        }
        let temporaries: Vec<PathBuf> = scratch.iter().map(|file| file.path().to_owned()).collect();
        crate::session_repair::stage_embedded_files(&mut self.session, &temporaries)?;
        let mut disk = DiskSourceAccess::with_options(options.clone());
        for (index, path) in temporaries.iter().enumerate() {
            disk.insert(SourceId(index as u64), path.clone());
        }
        let disk = Arc::new(disk);
        let mut verified = Par3RepairSession::new(self.id, disk.clone(), options.clone())?;
        for packet in self.session.input.packets().filter(|packet| {
            packet.metadata().is_some()
                || packet
                    .payload()
                    .is_some_and(|payload| matches!(payload.kind(), PayloadKind::Recovery { .. }))
        }) {
            verified.merge(packet.clone())?;
        }
        for (index, file) in layout.files().iter().enumerate() {
            verified.bind_file(&file.path, SourceId(index as u64))?;
        }
        if verified.assess()?.status != RepairStatus::Complete {
            return Err(EngineError::InvalidState("rebuilt hosts are incomplete"));
        }
        let mut carriers = Vec::new();
        let mut markers = Vec::new();
        let mut reports_pending = Vec::new();
        for &index in &needed {
            let host = &self.hosts[index];
            let marker = crate::session_repair::ScratchFile::new(
                &scratch_directory.join(format!("carrier-{index}")),
                &options,
            )?;
            let carrier_path = marker.path().with_extension("carrier");
            markers.push(marker);
            let plan =
                CarrierPlan::derived(&mut verified, self.metadata.clone(), host.recovery.clone())?;
            if plan.output_bytes() != host.carrier {
                return Err(EngineError::InvalidState("derived carrier length differs"));
            }
            reports_pending.push(plan.execute(&mut verified, &carrier_path, scratch_directory)?);
            carriers.push(carrier_path);
        }
        let mut reports = Vec::new();
        let result = (|| -> EngineResult<()> {
            for ((&index, carrier_path), report) in
                needed.iter().zip(&carriers).zip(reports_pending.drain(..))
            {
                let host = self.hosts[index].clone();
                let carrier = std::fs::read(carrier_path)?;
                let source = SourceId(host.file as u64);
                let ctx = host_ctx(
                    disk.as_ref(),
                    source,
                    self.spec,
                    host.gap.end,
                    host.length,
                    &options,
                    self.crypto.as_deref(),
                )?;
                let body = crc_register(disk.as_ref(), source, 0..host.gap.start, &options)?;
                let region = render(
                    self.spec,
                    self.crypto.as_deref(),
                    self.id,
                    index,
                    &ctx,
                    body,
                    &carrier,
                )?;
                if region.len() as u64 != host.gap.end - host.gap.start {
                    return Err(EngineError::InvalidState(
                        "rendered region differs from the gap",
                    ));
                }
                let output = std::fs::OpenOptions::new()
                    .write(true)
                    .open_budgeted(&temporaries[host.file], &options)?;
                output.write_all_at(host.gap.start, &region)?;
                // Positional writes leave nothing buffered to flush.
                drop(output);
                let proof = crate::evidence::verify_source(
                    layout.clone(),
                    host.file,
                    disk.as_ref(),
                    source,
                    &options,
                )?;
                if !proof.protected_complete() {
                    return Err(EngineError::InvalidState(
                        "repaired host failed verification",
                    ));
                }
                reports.push(Repaired {
                    name: host.name.clone(),
                    path: destinations[index].clone(),
                    data_rebuilt: !host.complete,
                    regenerated: report.recovery_packets,
                    restoration: report.restoration,
                });
            }
            let mut installed: Vec<&Path> = Vec::new();
            for &index in &needed {
                let file = self.hosts[index].file;
                if let Err(error) = std::fs::hard_link(&temporaries[file], &destinations[index])
                    .or_else(|_| {
                        std::fs::copy(&temporaries[file], &destinations[index]).map(|_| ())
                    })
                {
                    for path in installed {
                        let _ = std::fs::remove_file(path);
                    }
                    return Err(error.into());
                }
                installed.push(&destinations[index]);
            }
            Ok(())
        })();
        for carrier in &carriers {
            let _ = std::fs::remove_file(carrier);
        }
        drop(markers);
        drop(scratch);
        result.map(|()| reports)
    }

    /// Write every host without its region to `destinations[k]` (absent),
    /// checked against the fingerprint the File packet recorded.
    pub fn remove(&mut self, destinations: &[PathBuf]) -> EngineResult<Vec<PathBuf>> {
        if destinations.len() != self.hosts.len() {
            return Err(EngineError::InvalidState("remove destination count"));
        }
        if let Some(host) = self.hosts.iter().find(|host| !host.complete) {
            return Err(EngineError::Unsupported(if host.source.is_none() {
                "a host is missing; repair before removing"
            } else {
                "a host is damaged; repair before removing"
            }));
        }
        if destinations
            .iter()
            .any(|d| std::fs::symlink_metadata(d).is_ok())
        {
            return Err(
                io::Error::new(io::ErrorKind::AlreadyExists, "remove output exists").into(),
            );
        }
        let options = self.session.options.clone();
        let layout = self.session.layout()?.expect("layout");
        let size = options.stripe_bytes.min(64 << 10);
        let mut buffer = vec![0; size];
        let mut written = Vec::new();
        let mut staged = Vec::new();
        let result = (|| -> EngineResult<()> {
            for (host, destination) in self.hosts.iter().zip(destinations) {
                let source = host.source.expect("bound");
                let temporary = crate::session_repair::stage_path(destination, &options)?;
                staged.push(temporary.clone());
                let mut output = std::fs::OpenOptions::new()
                    .write(true)
                    .open_budgeted(&temporary, &options)?;
                let mut hash = FingerprintHasher::new();
                copy(
                    self.raw.as_ref(),
                    source,
                    0..host.gap.start,
                    &mut output,
                    &mut buffer,
                    Some(&mut hash),
                    &options,
                )?;
                copy(
                    self.raw.as_ref(),
                    source,
                    host.gap.end..host.length,
                    &mut output,
                    &mut buffer,
                    Some(&mut hash),
                    &options,
                )?;
                if hash.finalize() != layout.files()[host.file].fingerprint {
                    return Err(EngineError::InvalidState(
                        "stripped host differs from the original",
                    ));
                }
                output.flush()?;
                drop(output);
                std::fs::hard_link(&temporary, destination)?;
                written.push(destination.clone());
            }
            Ok(())
        })();
        for path in staged {
            let _ = std::fs::remove_file(path);
        }
        if result.is_err() {
            for path in &written {
                let _ = std::fs::remove_file(path);
            }
        }
        result.map(|()| written)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compensation_hits_a_target() {
        let body: Vec<u8> = (0..333u32).map(|v| (v * 13) as u8).collect();
        let state = crc_update(!0, &body);
        let x = solve_affine(&|x: &[u8; 16]| !crc_update(state, x), 0x1234_5678).expect("solvable");
        let mut all = body.clone();
        all.extend_from_slice(&x);
        assert_eq!(crc32(&all), 0x1234_5678);
    }

    #[test]
    fn region_lengths_match_their_spec() {
        let spec = Spec {
            format: Format::Rar4,
            layout: Layout::Service,
            encrypted: false,
        };
        let carrier = vec![7u8; 333];
        let region = render(
            spec,
            None,
            InputSetId([1; 8]),
            0,
            &HostCtx {
                data_crc: Some(0xdead_beef),
                rar5_key: None,
            },
            crc_update(!0, b"body"),
            &carrier,
        )
        .expect("render");
        assert_eq!(region.len() as u64, spec.gap(333));
        assert_eq!(u32_at(&region, 16).unwrap(), crc32(&region[44..]));
        assert_eq!(
            (crc32(&region[2..44]) & 0xffff) as u16,
            u16_at(&region, 0).unwrap()
        );
        let mut all = b"body".to_vec();
        all.extend_from_slice(&region);
        assert_eq!(crc32(&all), 0xdead_beef);
    }

    #[test]
    fn plain_rar4_compensation_solves_across_lengths() {
        let spec = Spec {
            format: Format::Rar4,
            layout: Layout::Service,
            encrypted: false,
        };
        for length in (1..2000u32).step_by(7) {
            let carrier: Vec<u8> = (0..length).map(|v| (v * 31 + length) as u8).collect();
            let target = length.wrapping_mul(0x9E37_79B9);
            let body = crc_update(!0, &length.to_le_bytes());
            let ctx = HostCtx {
                data_crc: Some(target),
                rar5_key: None,
            };
            let region = render(spec, None, InputSetId([2; 8]), 0, &ctx, body, &carrier)
                .unwrap_or_else(|error| panic!("length {length}: {error:?}"));
            assert_eq!(!crc_update(body, &region), target);
        }
    }
}
