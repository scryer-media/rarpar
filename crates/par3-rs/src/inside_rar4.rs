// facts. It is not part of the crate's supported scope, it is not mentioned in
// the README or the crate docs, and its on-disk layout may change or be
// dropped without notice.

//! **EXPERIMENTAL** PAR-inside for RAR4 archives, and for RAR5 archives whose
//! headers are encrypted (`-hp`).
//!
//! The RAR4 service layout is one `NEWSUB` block (`HEAD_TYPE` 0x7A) named
//! `PAR3`, with `LHD_SOLID` clear, inserted just before the end-of-archive
//! block, or at the end of the file when the archive has no end block (`-en`).
//! Its data area is the PAR3 carrier followed by eight free bytes, the header
//! ends with eight free bytes of sub-block data, and `FILE_CRC` is the data
//! area's CRC32. When the end block records a CRC32 of the archive data
//! (`EARC_DATACRC`, set on volumes), the free bytes are chosen so that CRC
//! still holds, so the end block is never rewritten and removal restores the
//! original byte for byte.
//!
//! With encrypted headers (`-hp`) the new header is encrypted the way RAR4
//! encrypts every header after the main one: an 8-byte salt, then the header
//! padded to the AES block and encrypted with AES-128-CBC keyed by the RAR3
//! KDF over the password and that salt. The carrier itself is encrypted the
//! way a RAR4 member is (`LHD_PASSWORD | LHD_SALT`, a salt of its own), so a
//! reader without the password sees neither the PAR3 packets nor the header.
//! The data area then ends with one extra cipher block that carries the
//! `EARC_DATACRC` compensation.
//!
//! For RAR5 with encrypted headers the service layout is a type-3 service
//! header named `PAR3`, encrypted like every RAR5 `-hp` header (a 16-byte IV,
//! then AES-256-CBC with the key the archive's encryption header derives), and
//! its data is the carrier encrypted with that key and an IV recorded in a
//! file-encryption extra record.
//!
//! The salts and IVs are derived from the input set id and the host index, so
//! a region can be regenerated byte for byte. The caller supplies the crypto
//! (KDFs and AES-CBC) through [`RarCipher`]; this crate links no crypto.
//!
//! [`Layout::Trailing`] appends the carrier after the archive instead, as the
//! RAR5 trailing layout does; it is never encrypted.

