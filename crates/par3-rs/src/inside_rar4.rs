/// Key derivation and AES-CBC supplied by the caller. The password lives in
/// the implementation.
pub trait RarCipher: Send + Sync {
    /// RAR3 KDF: AES-128 key and IV for an 8-byte salt.
    fn rar4_key(&self, salt: &[u8; 8]) -> ([u8; 16], [u8; 16]);
    /// RAR5 KDF: AES-256 key for a 16-byte salt and log2 iteration count.
    fn rar5_key(&self, salt: &[u8; 16], lg2_count: u8) -> [u8; 32];
    /// AES-CBC encryption in place; the key length picks AES-128 or AES-256,
    /// and `data` is a whole number of blocks.
    fn cbc_encrypt(&self, key: &[u8], iv: &[u8; 16], data: &mut [u8]);
    /// AES-CBC decryption in place, as [`Self::cbc_encrypt`].
    fn cbc_decrypt(&self, key: &[u8], iv: &[u8; 16], data: &mut [u8]);
}

type Rar4Key = ([u8; 16], [u8; 16]);
type Rar5KdfCache = HashMap<([u8; 16], u8), [u8; 32]>;
/// Salt, log2 count and IV of a RAR5 file-encryption record.
type Rar5CryptRecord = ([u8; 16], u8, [u8; 16]);

/// A [`RarCipher`] with KDF results cached per salt.
pub struct Crypto {
    cipher: Box<dyn RarCipher>,
    rar4: Mutex<HashMap<[u8; 8], Rar4Key>>,
    rar5: Mutex<Rar5KdfCache>,
}

impl Crypto {
    /// Wrap a cipher.
    pub fn new(cipher: Box<dyn RarCipher>) -> Arc<Self> {
        Arc::new(Self {
            cipher,
            rar4: Mutex::new(HashMap::new()),
            rar5: Mutex::new(HashMap::new()),
        })
    }

    fn rar4(&self, salt: &[u8; 8]) -> Rar4Key {
        let mut cache = self.rar4.lock().expect("kdf cache");
        *cache
            .entry(*salt)
            .or_insert_with(|| self.cipher.rar4_key(salt))
    }

    fn rar5(&self, salt: &[u8; 16], lg2: u8) -> [u8; 32] {
        let mut cache = self.rar5.lock().expect("kdf cache");
        *cache
            .entry((*salt, lg2))
            .or_insert_with(|| self.cipher.rar5_key(salt, lg2))
    }

    fn encrypt(&self, key: &[u8], iv: &[u8; 16], data: &mut [u8]) {
        debug_assert!(data.len().is_multiple_of(16));
        if !data.is_empty() {
            self.cipher.cbc_encrypt(key, iv, data);
        }
    }

    fn decrypt(&self, key: &[u8], iv: &[u8; 16], data: &mut [u8]) {
        debug_assert!(data.len().is_multiple_of(16));
        if !data.is_empty() {
            self.cipher.cbc_decrypt(key, iv, data);
        }
    }
}

/// Archive format of a host.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Format {
    /// RAR 1.5–4.x.
    Rar4,
    /// RAR 5.0.
    Rar5,
}

/// Where the carrier sits.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Layout {
    /// After the archive.
    Trailing,
    /// A `PAR3` service block before the end block.
    Service,
}

/// The region shape of a set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Spec {
    /// Host format.
    pub format: Format,
    /// Region layout.
    pub layout: Layout,
    /// Hosts have encrypted headers; a service region is encrypted too.
    pub encrypted: bool,
}

fn align16(value: u64) -> u64 {
    value.div_ceil(16) * 16
}

impl Spec {
    /// Region bytes before the carrier.
    pub fn prefix(&self, carrier: u64) -> u64 {
        match (self.layout, self.format, self.encrypted) {
            (Layout::Trailing, ..) => 0,
            (Layout::Service, Format::Rar4, false) => 44,
            (Layout::Service, Format::Rar4, true) => 8 + 48,
            (Layout::Service, Format::Rar5, false) => {
                r5::region_header(r5::Rar5Layout::Service, carrier).len() as u64
            }
            (Layout::Service, Format::Rar5, true) => {
                16 + align16(rar5_service_plain(carrier, &[0; 16], 0, &[0; 16]).len() as u64)
            }
        }
    }

    /// Region bytes after the carrier.
    pub fn suffix(&self, carrier: u64) -> u64 {
        match (self.layout, self.format, self.encrypted) {
            (Layout::Trailing, ..) => 0,
            (Layout::Service, Format::Rar4, false) => 8,
            (Layout::Service, Format::Rar4, true) => align16(carrier) - carrier + 16,
            (Layout::Service, Format::Rar5, false) => 0,
            (Layout::Service, Format::Rar5, true) => align16(carrier) - carrier,
        }
    }

    fn gap(&self, carrier: u64) -> u64 {
        self.prefix(carrier) + carrier + self.suffix(carrier)
    }
}

