/// Recovery Data packet overhead: header 48, root 16, matrix 16, index 8.
const RECOVERY_OVERHEAD: u64 = 88;
/// Longest caller framing in front of a carrier that opening looks for.
pub const MAX_FRAMING: u64 = 4096;

/// How recovery packets are distributed over the hosts of a set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum Placement {
    /// One set; every host holds the metadata and an even share of recovery.
    Spread,
    /// One set; every host holds the metadata, the last holds all recovery.
    Last,
    /// One set per host, each with its own recovery.
    Independent,
}

/// The caller's container side of an insertion: the host bytes around each
/// carrier, and the framing in front of it.
///
/// Host `k` is written as [`Self::write_body`], [`Self::write_prefix`], the
/// carrier (written by this module), then [`Self::write_tail`]. The body and
/// tail must be the host's own bytes before and from its split: they are
/// checked against the fingerprint the set records. When the output is
/// staged as a filesystem clone of the host, the body is already in place
/// and [`Self::write_body`] is not called.
pub trait InsertFraming {
    /// Framing bytes in front of a carrier of `carrier` bytes in host `host`.
    fn prefix_len(&self, host: usize, carrier: u64) -> u64;
    /// Write host `host`'s bytes before its split.
    fn write_body(&mut self, host: usize, carrier: u64, out: &mut dyn Write) -> io::Result<()>;
    /// Write the framing of a carrier of `carrier` bytes in host `host`:
    /// exactly [`Self::prefix_len`] bytes.
    fn write_prefix(&mut self, host: usize, carrier: u64, out: &mut dyn Write) -> io::Result<()>;
    /// Write host `host`'s bytes from its split on.
    fn write_tail(&mut self, host: usize, carrier: u64, out: &mut dyn Write) -> io::Result<()>;
}

/// The caller's container side of opening and repairing a set.
pub trait CarrierFraming {
    /// Whether framing of `prefix` bytes (at most [`MAX_FRAMING`]) can stand
    /// in front of a carrier of `carrier` bytes: true for what
    /// [`InsertFraming::prefix_len`] gave. A caller that cannot tell which
    /// of a few framings a damaged host had may accept each; opening takes
    /// the shortest that leaves a carrier of whole packets.
    fn fits(&self, prefix: u64, carrier: u64) -> bool;
    /// The framing bytes of a carrier of `carrier` bytes in the host file at
    /// `file`, whose bytes outside its carrier gap are the host's protected
    /// bytes. `Ok(None)` when the caller cannot produce them (a key it does
    /// not hold, for example): opening then reports the framing unchecked,
    /// and repairing that host is refused.
    fn prefix(&self, file: &Path, carrier: u64) -> EngineResult<Option<Vec<u8>>>;
    /// What the container says about a candidate file before it is scanned.
    fn locate(&self, file: &Path) -> CarrierHint {
        let _ = file;
        CarrierHint::default()
    }
}

/// What a container says about a candidate file.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CarrierHint {
    /// Position in a volume family, zero for the first. Binds a missing
    /// host of the same length when neither its name nor its packets do.
    pub volume: Option<u64>,
    /// Where the carrier's framing starts; scanning begins there, and falls
    /// back to the whole file when nothing is found.
    pub carrier_from: Option<u64>,
}

/// Recovery counts per host of one shared set, for a placement and a total.
///
/// # Errors
///
/// [`EngineError::Unsupported`] for [`Placement::Independent`], which is
/// one set per host: call [`insert_set`] once per host with that host's own
/// recovery count instead.
pub fn placement_counts(placement: Placement, hosts: usize, total: u64) -> EngineResult<Vec<u64>> {
    if hosts == 0 {
        return Err(EngineError::InvalidState("insert host count"));
    }
    match placement {
        Placement::Last => {
            let mut counts = vec![0; hosts];
            counts[hosts - 1] = total;
            Ok(counts)
        }
        Placement::Spread => {
            let base = total / hosts as u64;
            let extra = total % hosts as u64;
            Ok((0..hosts as u64)
                .map(|index| base + u64::from(index < extra))
                .collect())
        }
        Placement::Independent => Err(EngineError::Unsupported(
            "independent placement inserts one set per host",
        )),
    }
}

/// One host described for insertion.
#[derive(Clone, Debug)]
pub struct EmbeddedHost {
    /// Existing host file.
    pub path: PathBuf,
    /// Name recorded in the File packet.
    pub name: String,
    /// Offset the carrier goes at: bytes before it stay in front of the
    /// framing, bytes from it on follow the carrier.
    pub split: u64,
    /// The revision the caller inspected; insertion refuses any other.
    snapshot: SourceSnapshot,
}

impl EmbeddedHost {
    /// Describe `path`, recording `name` (a single safe file name, see
    /// [`validate_host_name`]). The file's revision is taken now, so call
    /// this before inspecting the container; [`Self::split`] starts at the
    /// end of the file until the caller sets it.
    pub fn new(path: &Path, name: &str, options: &ExecutionOptions) -> EngineResult<Self> {
        validate_host_name(name)?;
        let disk = disk_access(std::slice::from_ref(&path.to_owned()), options);
        let snapshot = disk
            .snapshot(SourceId(0))?
            .ok_or(EngineError::Unavailable {
                source_id: SourceId(0),
                offset: 0,
            })?;
        Ok(Self {
            path: path.to_owned(),
            name: name.to_owned(),
            split: snapshot.len,
            snapshot,
        })
    }

    /// Length of the host file at the revision described.
    pub fn len(&self) -> u64 {
        self.snapshot.len
    }

    /// Whether the host file is empty.
    pub fn is_empty(&self) -> bool {
        self.snapshot.len == 0
    }

    /// Refuse a host file that changed since [`Self::new`].
    pub fn unchanged(&self, options: &ExecutionOptions) -> EngineResult<()> {
        let disk = disk_access(std::slice::from_ref(&self.path), options);
        if disk.snapshot(SourceId(0))? != Some(self.snapshot) {
            return Err(EngineError::Unsupported(
                "host changed since it was inspected",
            ));
        }
        Ok(())
    }
}

/// Bytes added to one host.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct EmbeddedInserted {
    /// Output written.
    pub path: PathBuf,
    /// Bytes added: the caller's framing and the carrier.
    pub region_bytes: u64,
    /// Recovery Data packets in the carrier.
    pub recovery_packets: u64,
    /// Input set the host belongs to.
    pub set: InputSetId,
}

/// Counts every byte written through it.
struct Counting<'a, W: Write + ?Sized> {
    inner: &'a mut W,
    written: u64,
}

impl<W: Write + ?Sized> Write for Counting<'_, W> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        let written = self.inner.write(bytes)?;
        self.written += written as u64;
        Ok(written)
    }
    fn flush(&mut self) -> io::Result<()> {
        self.inner.flush()
    }
}

/// Hashes every byte written through it, when asked to.
struct Hashing<'a, W: Write + ?Sized> {
    inner: &'a mut W,
    hash: Option<&'a mut FingerprintHasher>,
}

impl<W: Write + ?Sized> Write for Hashing<'_, W> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        let written = self.inner.write(bytes)?;
        if let Some(hash) = self.hash.as_deref_mut() {
            hash.update(&bytes[..written]);
        }
        Ok(written)
    }
    fn flush(&mut self) -> io::Result<()> {
        self.inner.flush()
    }
}

/// Insert one set over `hosts`, writing host `k` with its framing and
/// carrier to `outputs[k]`, which must not exist. `counts[k]` recovery
/// packets go into host `k`; their sum is `options.recovery_count`. The
/// caller's `framing` writes everything but the carriers.
///
/// Every output is staged beside its destination (a filesystem clone of the
/// host where possible), checked against the set's fingerprint for the host,
/// and only then linked into place; a failure leaves no output behind.
pub fn insert_set(
    hosts: &[EmbeddedHost],
    outputs: &[PathBuf],
    counts: &[u64],
    options: CreationOptions,
    scratch_directory: &Path,
    framing: &mut dyn InsertFraming,
) -> EngineResult<Vec<EmbeddedInserted>> {
    if options.codec != CreationCodec::Cauchy || options.store_data {
        return Err(EngineError::Unsupported(
            "PAR-inside requires Cauchy recovery without Data packets",
        ));
    }
    if hosts.len() != outputs.len() || hosts.len() != counts.len() || hosts.is_empty() {
        return Err(EngineError::InvalidState("insert host count"));
    }
    // The carrier records no recovery-index base; opening a set whose
    // recovery packets are all lost assumes zero.
    if options.first_recovery != 0 {
        return Err(EngineError::Unsupported(
            "PAR-inside recovery indices start at zero",
        ));
    }
    let names: BTreeSet<_> = hosts.iter().map(|host| host.name.as_str()).collect();
    if names.len() != hosts.len() {
        return Err(EngineError::Unsupported("duplicate host names"));
    }
    let execution = options.execution.clone();
    let mut disk = DiskSourceAccess::with_options(execution.clone());
    for (index, host) in hosts.iter().enumerate() {
        disk.insert(SourceId(index as u64), host.path.clone());
    }
    let disk: Arc<dyn SourceAccess> = Arc::new(disk);
    let mut views = BTreeMap::new();
    let mut sources = Vec::new();
    let mut tails = Vec::new();
    let mut splits = Vec::new();
    for (index, host) in hosts.iter().enumerate() {
        let snapshot = disk
            .snapshot(SourceId(index as u64))?
            .ok_or(EngineError::Unavailable {
                source_id: SourceId(index as u64),
                offset: 0,
            })?;
        // The split belongs to the inspected revision.
        if snapshot != host.snapshot {
            return Err(EngineError::Unsupported(
                "host changed since it was inspected",
            ));
        }
        let split = host.split;
        if split > snapshot.len {
            return Err(EngineError::InvalidState("host split is past its end"));
        }
        let body = SourceId(2 * index as u64);
        views.insert(body, (SourceId(index as u64), snapshot, 0..split));
        sources.push(CreationSource {
            name: host.name.clone(),
            source: body,
        });
        let tail = split < snapshot.len;
        if tail {
            let id = SourceId(2 * index as u64 + 1);
            views.insert(id, (SourceId(index as u64), snapshot, split..snapshot.len));
            sources.push(CreationSource {
                name: format!(".embedded-tail-{index}"),
                source: id,
            });
        }
        tails.push(tail);
        splits.push((split, snapshot));
    }
    let views: Arc<dyn SourceAccess> = Arc::new(HostViews {
        access: disk.clone(),
        views,
    });
    let mut plan = CreationPlan::build_in_source_order(views, &sources, options)?;
    let gaps = plan.embedded_set_layout(&tails, counts, &|host, carrier| {
        framing.prefix_len(host, carrier)
    })?;
    for output in outputs {
        if std::fs::symlink_metadata(output).is_ok() {
            return Err(io::Error::new(io::ErrorKind::AlreadyExists, "PAR3 output exists").into());
        }
    }
    let fingerprints = plan.embedded_fingerprints();
    let size = execution.stripe_bytes.min(64 << 10);
    let mut staged: Vec<PathBuf> = Vec::new();
    let result = (|| -> EngineResult<Vec<EmbeddedInserted>> {
        let mut writers = Vec::new();
        let mut copied = Vec::new();
        for (index, output) in outputs.iter().enumerate() {
            let (split, _) = splits[index];
            let source = SourceId(index as u64);
            let (mut file, cloned) = stage(disk.as_ref(), source, output, &execution, &mut staged)?;
            // A clone already holds the body; its bytes are the inspected
            // revision's, which the snapshot check after the copy confirms.
            let mut hash = (!cloned).then(FingerprintHasher::new);
            if cloned {
                file.set_len(split)?;
                io::Seek::seek(&mut file, io::SeekFrom::Start(split))?;
            } else {
                let mut out = BufWriter::with_capacity(size, &mut file);
                let mut counted = Counting {
                    inner: &mut out,
                    written: 0,
                };
                framing.write_body(
                    index,
                    gaps[index].1,
                    &mut Hashing {
                        inner: &mut counted,
                        hash: hash.as_mut(),
                    },
                )?;
                if counted.written != split {
                    return Err(EngineError::InvalidState(
                        "framing wrote a body of another length",
                    ));
                }
                out.flush()?;
            }
            copied.push(hash);
            writers.push(BufWriter::with_capacity(
                size,
                AuthenticatingWriter::new(file, plan.input_set_id(), execution.clone()),
            ));
        }
        plan.write_embedded_set(
            &mut writers,
            scratch_directory,
            |index, writer| {
                writer.flush()?;
                let mut counted = Counting {
                    inner: writer.get_mut().get_mut(),
                    written: 0,
                };
                framing.write_prefix(index, gaps[index].1, &mut counted)?;
                if counted.written != gaps[index].0 {
                    return Err(EngineError::InvalidState(
                        "framing length differs from its declared length",
                    ));
                }
                Ok(())
            },
            |index, writer| {
                writer.flush()?;
                writer.get_ref().finish(gaps[index].1)?;
                Ok(())
            },
        )?;
        let mut reports = Vec::new();
        for (index, writer) in writers.into_iter().enumerate() {
            let mut file = writer
                .into_inner()
                .map_err(io::IntoInnerError::into_error)?
                .into_inner();
            let (split, snapshot) = splits[index];
            let source = SourceId(index as u64);
            let mut hash = copied[index].take();
            let mut out = BufWriter::with_capacity(size, &mut file);
            let mut counted = Counting {
                inner: &mut out,
                written: 0,
            };
            framing.write_tail(
                index,
                gaps[index].1,
                &mut Hashing {
                    inner: &mut counted,
                    hash: hash.as_mut(),
                },
            )?;
            if counted.written != snapshot.len - split {
                return Err(EngineError::InvalidState(
                    "framing wrote a tail of another length",
                ));
            }
            out.flush()?;
            drop(out);
            crate::source::ensure_snapshot(disk.as_ref(), source, snapshot)?;
            if let Some(hash) = hash
                && hash.finalize() != fingerprints[index]
            {
                return Err(EngineError::InvalidState(
                    "embedded output failed verification",
                ));
            }
            file.flush()?;
            drop(file);
            reports.push(EmbeddedInserted {
                path: outputs[index].clone(),
                region_bytes: gaps[index].0 + gaps[index].1,
                recovery_packets: counts[index],
                set: plan.input_set_id(),
            });
        }
        // Every host is finished and verified before any is linked into
        // place, and a failed link removes the outputs linked before it, so
        // a failed insertion leaves no final output behind.
        link_all(&staged, outputs)?;
        Ok(reports)
    })();
    for path in staged {
        let _ = std::fs::remove_file(path);
    }
    result
}

/// Link each finished `staged[k]` to the absent `outputs[k]`. On a failure,
/// remove the outputs this call already linked, so none is left behind.
pub(crate) fn link_all(staged: &[PathBuf], outputs: &[PathBuf]) -> EngineResult<()> {
    for (position, (temporary, output)) in staged.iter().zip(outputs).enumerate() {
        let linked =
            injected_install_failure(position).and_then(|()| std::fs::hard_link(temporary, output));
        if let Err(error) = linked {
            for earlier in &outputs[..position] {
                let _ = std::fs::remove_file(earlier);
            }
            return Err(error.into());
        }
    }
    Ok(())
}

#[cfg(test)]
thread_local! {
    /// Fails the install of the output at this position in its call, so
    /// tests can reach the rollback of earlier installs.
    static FAIL_INSTALL_AT: std::cell::Cell<Option<usize>> = const { std::cell::Cell::new(None) };
}

/// A test-injected failure for the install at `position`; never fails
/// outside tests.
fn injected_install_failure(position: usize) -> io::Result<()> {
    #[cfg(test)]
    if FAIL_INSTALL_AT.with(std::cell::Cell::get) == Some(position) {
        return Err(io::Error::other("injected install failure"));
    }
    let _ = position;
    Ok(())
}

/// Stage `destination` as a clone of the source where the filesystem allows,
/// otherwise as an empty file. Records the staging path in `staged`.
pub(crate) fn stage(
    access: &dyn SourceAccess,
    source: SourceId,
    destination: &Path,
    options: &ExecutionOptions,
    staged: &mut Vec<PathBuf>,
) -> EngineResult<(File, bool)> {
    #[cfg(target_os = "macos")]
    if let Some(original) = access.open_file(source)?
        && let Some(temporary) = crate::session_repair::clone_stage_path(destination, &*original.0)?
    {
        staged.push(temporary.clone());
        let output = std::fs::OpenOptions::new()
            .write(true)
            .open_budgeted(&temporary, options)?;
        options.diagnostics.note_clone();
        return Ok((output, true));
    }
    #[cfg(not(target_os = "macos"))]
    let _ = (access, source);
    let temporary = crate::session_repair::stage_path(destination, options)?;
    staged.push(temporary.clone());
    let output = std::fs::OpenOptions::new()
        .write(true)
        .open_budgeted(&temporary, options)?;
    Ok((output, false))
}

/// Install the verified `temporary` at the absent `destination` without
/// replacing anything there. A hard link when both are on one filesystem;
/// across filesystems, a copy staged beside `destination` and compared byte
/// for byte with `temporary` before it is linked into place.
fn install(temporary: &Path, destination: &Path, options: &ExecutionOptions) -> EngineResult<()> {
    match std::fs::hard_link(temporary, destination) {
        Err(error) if error.kind() == io::ErrorKind::CrossesDevices => {
            install_by_copy(temporary, destination, options)
        }
        result => Ok(result?),
    }
}

fn install_by_copy(
    temporary: &Path,
    destination: &Path,
    options: &ExecutionOptions,
) -> EngineResult<()> {
    let staged = crate::session_repair::stage_path(destination, options)?;
    let result = (|| -> EngineResult<()> {
        use std::io::Read;
        let mut from = File::open(temporary, options)?;
        let mut output = std::fs::OpenOptions::new()
            .write(true)
            .truncate(true)
            .open_budgeted(&staged, options)?;
        let length = from.metadata()?.len();
        let size = options.stripe_bytes.clamp(1, 64 << 10);
        let mut buffer = vec![0; size];
        let mut check = vec![0; size];
        let mut at = 0;
        while at < length {
            options.cancel.check()?;
            let take = (length - at).min(size as u64) as usize;
            from.read_exact(&mut buffer[..take])?;
            output.write_all(&buffer[..take])?;
            at += take as u64;
        }
        output.flush()?;
        drop((from, output));
        let mut from = File::open(temporary, options)?;
        let mut copied = File::open(&staged, options)?;
        if copied.metadata()?.len() != length {
            return Err(EngineError::InvalidState("installed copy differs"));
        }
        at = 0;
        while at < length {
            options.cancel.check()?;
            let take = (length - at).min(size as u64) as usize;
            from.read_exact(&mut buffer[..take])?;
            copied.read_exact(&mut check[..take])?;
            if buffer[..take] != check[..take] {
                return Err(EngineError::InvalidState("installed copy differs"));
            }
            at += take as u64;
        }
        drop((from, copied));
        std::fs::hard_link(&staged, destination)?;
        Ok(())
    })();
    let _ = std::fs::remove_file(&staged);
    result
}

pub(crate) struct HostViews {
    pub(crate) access: Arc<dyn SourceAccess>,
    pub(crate) views: BTreeMap<SourceId, (SourceId, SourceSnapshot, Range<u64>)>,
}

impl HostViews {
    fn view(&self, source: SourceId) -> io::Result<&(SourceId, SourceSnapshot, Range<u64>)> {
        self.views
            .get(&source)
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "unknown host view"))
    }
}

impl SourceAccess for HostViews {
    fn snapshot(&self, source: SourceId) -> io::Result<Option<SourceSnapshot>> {
        let (host, _, range) = self.view(source)?;
        Ok(self.access.snapshot(*host)?.map(|snapshot| SourceSnapshot {
            len: snapshot.len.min(range.end).saturating_sub(range.start),
            generation: snapshot.generation,
        }))
    }
    fn read_at(&self, source: SourceId, offset: u64, output: &mut [u8]) -> io::Result<usize> {
        let (host, _, range) = self.view(source)?;
        let length = range.end - range.start;
        if offset >= length {
            return Ok(0);
        }
        let take = (length - offset).min(output.len() as u64) as usize;
        self.access
            .read_at(*host, range.start + offset, &mut output[..take])
    }
    fn next_available(&self, source: SourceId, offset: u64) -> io::Result<Option<Range<u64>>> {
        let (host, _, range) = self.view(source)?;
        if offset >= range.end - range.start {
            return Ok(None);
        }
        Ok(self
            .access
            .next_available(*host, range.start + offset)?
            .and_then(|available| {
                let start = available.start.max(range.start);
                let end = available.end.min(range.end);
                (start < end).then_some(start - range.start..end - range.start)
            }))
    }
}

/// Every authenticated packet of any set in `source`, scanning from `from`.
pub(crate) fn scan(
    access: Arc<dyn SourceAccess>,
    source: SourceId,
    from: u64,
    options: &ExecutionOptions,
) -> EngineResult<Vec<IngestedPacket>> {
    let mut scanner = PacketScanner::new(access, source, options.clone(), ScanLimits::default())?;
    if from != 0 {
        scanner.seek(from)?;
    }
    let mut packets = Vec::new();
    loop {
        match scanner.poll()? {
            ScanEvent::Packet(packet) => packets.push(packet),
            ScanEvent::End | ScanEvent::NeedData { .. } => return Ok(packets),
        }
    }
}

/// One host of an opened set.
#[derive(Clone, Debug)]
pub struct EmbeddedHostState {
    /// Name recorded in the File packet.
    pub name: String,
    /// File currently bound to this host, if any was found.
    pub path: Option<PathBuf>,
    /// How the file was matched to the host.
    pub matched_by: Option<&'static str>,
    /// Index in the set's layout.
    file: usize,
    source: Option<SourceId>,
    /// The unprotected chunk holding the framing and the carrier.
    pub gap: Range<u64>,
    /// Framing bytes at the start of the gap.
    pub prefix: u64,
    /// Expected file length.
    pub length: u64,
    /// Recovery indices this host's carrier holds.
    pub recovery: Range<u64>,
    /// Protected bytes verified.
    pub complete: bool,
    /// Damaged or missing protected ranges, in file coordinates.
    pub unresolved: Vec<Range<u64>>,
    /// Carrier packets found at their exact offsets.
    pub packets_found: u64,
    /// Carrier packets the layout calls for.
    pub packets_expected: u64,
    /// Every carrier packet is at its slot and the file has its length.
    pub carrier_intact: bool,
    /// The caller's framing matches what [`CarrierFraming::prefix`] rebuilds;
    /// `None` when it was not checked (a missing or damaged host, or framing
    /// the caller could not produce).
    pub framing_intact: Option<bool>,
}

impl EmbeddedHostState {
    /// The framing and carrier are known to be byte-exact.
    pub fn region_intact(&self) -> bool {
        self.carrier_intact && self.framing_intact != Some(false)
    }
}

/// One opened embedded carrier set.
pub struct EmbeddedSet {
    /// Input set.
    pub id: InputSetId,
    /// Hosts in set order.
    pub hosts: Vec<EmbeddedHostState>,
    /// Overall readiness.
    pub status: RepairStatus,
    /// Lost protected blocks.
    pub lost_blocks: u64,
    /// Additional recovery blocks needed when not ready.
    pub additional: u64,
    /// Recovery packets usable now.
    pub recovery_available: u64,
    session: Par3RepairSession,
    metadata: Vec<Vec<u8>>,
}

pub(crate) fn disk_access(paths: &[PathBuf], options: &ExecutionOptions) -> DiskSourceAccess {
    let mut disk = DiskSourceAccess::with_options(options.clone());
    for (index, path) in paths.iter().enumerate() {
        disk.insert(SourceId(index as u64), path.clone());
    }
    disk
}

pub(crate) struct Candidate {
    pub(crate) path: PathBuf,
    pub(crate) source: SourceId,
    pub(crate) volume: Option<u64>,
    pub(crate) packets: Vec<IngestedPacket>,
    /// Indices into `packets` per input set, so opening one set walks its own
    /// packets rather than every packet of every set the file carries.
    by_set: HashMap<InputSetId, Vec<usize>>,
}

impl Candidate {
    pub(crate) fn new(
        path: PathBuf,
        source: SourceId,
        volume: Option<u64>,
        packets: Vec<IngestedPacket>,
    ) -> Self {
        let mut by_set: HashMap<InputSetId, Vec<usize>> = HashMap::new();
        for (index, packet) in packets.iter().enumerate() {
            by_set.entry(packet.input_set_id()).or_default().push(index);
        }
        Candidate {
            path,
            source,
            volume,
            packets,
            by_set,
        }
    }

    /// This file's packets of set `id`, in scan order.
    pub(crate) fn packets_of(&self, id: InputSetId) -> impl Iterator<Item = &IngestedPacket> {
        self.by_set
            .get(&id)
            .into_iter()
            .flatten()
            .map(|&index| &self.packets[index])
    }

    pub(crate) fn carries(&self, id: InputSetId) -> bool {
        self.by_set.contains_key(&id)
    }

    pub(crate) fn carries_other_than(&self, id: InputSetId) -> bool {
        self.by_set.keys().any(|other| *other != id)
    }
}

pub(crate) fn file_name(path: &Path) -> Option<&str> {
    path.file_name().and_then(|name| name.to_str())
}

/// Check that a host name recorded in a set is one safe file name: a single
/// component, with no `/`, that passes
/// [`crate::paths::validate_relative_path`]. A recorded name comes from the
/// set's own packets, so an absolute name or one with `..` would leave the
/// directory it is resolved in.
pub fn validate_host_name(name: &str) -> EngineResult<()> {
    if name.contains('/') {
        return Err(EngineError::Unsupported(
            "recorded host name is not a single file name",
        ));
    }
    crate::paths::validate_relative_path(name)?;
    Ok(())
}

/// Open every set found in `paths`, with the caller's `framing`. Hosts
/// recorded in a set but absent from `paths` are looked up next to the given
/// files under their recorded names and, when the given files were renamed,
/// under the renamed stem. A recorded name that is not one safe file name
/// ([`validate_host_name`]) is never looked up.
pub fn open(
    paths: &[PathBuf],
    options: &ExecutionOptions,
    framing: &dyn CarrierFraming,
) -> EngineResult<Vec<EmbeddedSet>> {
    // `known` keeps the given order; `seen` answers membership so a set with
    // many hosts does not rescan the list for every path.
    let mut known: Vec<PathBuf> = Vec::new();
    let mut seen: HashSet<PathBuf> = HashSet::new();
    for path in paths {
        if seen.insert(path.clone()) {
            known.push(path.clone());
        }
    }
    let mut candidates = Vec::new();
    let shared: Arc<dyn SourceAccess> = Arc::new(disk_access(&known, options));
    for (index, path) in known.iter().enumerate() {
        if path.is_file() {
            candidates.push(candidate(
                &shared,
                path.clone(),
                SourceId(index as u64),
                options,
                framing,
            )?);
        }
    }
    // Names recorded in any set, resolved next to the given files.
    let mut extra = Vec::new();
    for set_names in recorded_names(&candidates, shared, options)? {
        for (name, renamed) in set_names {
            for directory in known.iter().filter_map(|path| path.parent()) {
                for name in [Some(&name), renamed.as_ref()]
                    .into_iter()
                    .flatten()
                    .filter(|name| validate_host_name(name).is_ok())
                {
                    let path = directory.join(name);
                    if !seen.contains(&path) && path.is_file() {
                        seen.insert(path.clone());
                        extra.push(path);
                    }
                }
            }
        }
    }
    // The discovery inventory holds authenticated packets and their memory
    // reservations; release it before the rescan builds the final one, so the
    // two are never charged to the budget together.
    drop(candidates);
    known.extend(extra);
    let access: Arc<dyn SourceAccess> = Arc::new(disk_access(&known, options));
    // Rescan everything through the final provider so packet origins agree.
    let mut candidates = Vec::new();
    for (index, path) in known.iter().enumerate() {
        if path.is_file() {
            candidates.push(candidate(
                &access,
                path.clone(),
                SourceId(index as u64),
                options,
                framing,
            )?);
        }
    }
    // Sets in order of first appearance; `listed` answers membership so a
    // carrier with many sets is not rescanned per packet.
    let mut ids: Vec<InputSetId> = Vec::new();
    let mut listed: HashSet<InputSetId> = HashSet::new();
    for candidate in &candidates {
        for packet in &candidate.packets {
            if listed.insert(packet.input_set_id()) {
                ids.push(packet.input_set_id());
            }
        }
    }
    if ids.is_empty() {
        return Err(EngineError::Unsupported("no PAR3 packets found"));
    }
    ids.into_iter()
        .map(|id| open_set(id, &candidates, access.clone(), options, framing))
        .collect()
}

fn candidate(
    access: &Arc<dyn SourceAccess>,
    path: PathBuf,
    source: SourceId,
    options: &ExecutionOptions,
    framing: &dyn CarrierFraming,
) -> EngineResult<Candidate> {
    let hint = framing.locate(&path);
    let from = hint.carrier_from.unwrap_or(0);
    let mut packets = scan(access.clone(), source, from, options)?;
    if packets.is_empty() && from != 0 {
        packets = scan(access.clone(), source, 0, options)?;
    }
    Ok(Candidate::new(path, source, hint.volume, packets))
}

/// A recorded host name and, when a sibling was renamed, the name it would
/// have under that sibling's stem.
type RecordedName = (String, Option<String>);

/// Recorded host names per set, each with the name it would have under the
/// stem of a renamed sibling.
fn recorded_names(
    candidates: &[Candidate],
    access: Arc<dyn SourceAccess>,
    options: &ExecutionOptions,
) -> EngineResult<Vec<Vec<RecordedName>>> {
    let mut sessions: BTreeMap<InputSetId, Par3RepairSession> = BTreeMap::new();
    for candidate in candidates {
        for packet in candidate
            .packets
            .iter()
            .filter(|packet| packet.metadata().is_some())
        {
            let id = packet.input_set_id();
            let session = match sessions.entry(id) {
                std::collections::btree_map::Entry::Occupied(entry) => entry.into_mut(),
                std::collections::btree_map::Entry::Vacant(entry) => {
                    entry.insert(Par3RepairSession::new(id, access.clone(), options.clone())?)
                }
            };
            session.merge(packet.clone())?;
        }
    }
    let mut sets = Vec::new();
    for mut session in sessions.into_values() {
        if let Some(layout) = session.layout()? {
            sets.push(
                layout
                    .files()
                    .iter()
                    .map(|file| file.path.clone())
                    .collect::<Vec<_>>(),
            );
        }
    }
    Ok(sets
        .into_iter()
        .map(|names| {
            // A candidate is paired only with the recorded names that share
            // its volume tail, and each distinct stem change is kept once, so
            // a volume set yields one mapping rather than one per volume pair.
            let mut by_tail: HashMap<&str, Vec<&str>> = HashMap::new();
            for recorded in &names {
                if let Some(tail) = volume_tail(recorded) {
                    by_tail.entry(tail).or_default().push(recorded);
                }
            }
            let mut renames: Vec<(String, String)> = Vec::new();
            let mut kept: HashSet<(String, String)> = HashSet::new();
            for actual in candidates
                .iter()
                .filter_map(|candidate| file_name(&candidate.path))
            {
                let paired = volume_tail(actual).and_then(|tail| by_tail.get(tail));
                for recorded in paired.into_iter().flatten() {
                    if let Some(change) = stem_change(recorded, actual)
                        && kept.insert(change.clone())
                    {
                        renames.push(change);
                    }
                }
            }
            names
                .iter()
                .map(|name| {
                    let renamed = renames.iter().find_map(|(old, new)| {
                        name.strip_prefix(old.as_str())
                            .map(|rest| format!("{new}{rest}"))
                    });
                    (name.clone(), renamed)
                })
                .collect()
        })
        .collect())
}

/// The part of a file name a renamed sibling keeps: from `.partN.` when the
/// name has one, otherwise from its last dot. `None` for a name without a
/// dot, which no stem change can come from.
fn volume_tail(name: &str) -> Option<&str> {
    if let Some(start) = name.rfind(".part") {
        let rest = &name[start + ".part".len()..];
        let digits = rest.len() - rest.trim_start_matches(|c: char| c.is_ascii_digit()).len();
        if digits > 0 && rest[digits..].starts_with('.') {
            return Some(&name[start..]);
        }
    }
    name.rfind('.').map(|start| &name[start..])
}

/// When `recorded` and `actual` differ only before a common suffix that
/// starts at a dot, the old and new stems.
fn stem_change(recorded: &str, actual: &str) -> Option<(String, String)> {
    if recorded == actual {
        return None;
    }
    // Whole characters only: a byte-wise suffix can end inside one.
    let common: usize = recorded
        .chars()
        .rev()
        .zip(actual.chars().rev())
        .take_while(|(a, b)| a == b)
        .map(|(a, _)| a.len_utf8())
        .sum();
    let suffix = &recorded[recorded.len() - common..];
    let dot = suffix.find(".part").or_else(|| suffix.find('.'))?;
    let keep = common - dot;
    let old = &recorded[..recorded.len() - keep];
    let new = &actual[..actual.len() - keep];
    (!old.is_empty() && !new.is_empty()).then(|| (old.to_owned(), new.to_owned()))
}

/// Consecutive recovery index ranges for hosts carrying `counts` packets each,
/// the first starting at `first`. `first` comes from an authenticated packet,
/// which may still carry any index: a range past `u64::MAX` is refused, never
/// wrapped.
pub(crate) fn recovery_ranges(first: u64, counts: &[u64]) -> EngineResult<Vec<Range<u64>>> {
    let mut base = first;
    counts
        .iter()
        .map(|&count| {
            let end = base
                .checked_add(count)
                .ok_or(EngineError::Unsupported("recovery index out of range"))?;
            let range = base..end;
            base = end;
            Ok(range)
        })
        .collect()
}

fn open_set(
    id: InputSetId,
    candidates: &[Candidate],
    access: Arc<dyn SourceAccess>,
    options: &ExecutionOptions,
    framing: &dyn CarrierFraming,
) -> EngineResult<EmbeddedSet> {
    let mut session = Par3RepairSession::new(id, access.clone(), options.clone())?;
    for candidate in candidates {
        for packet in candidate.packets_of(id) {
            session.merge(packet.clone())?;
        }
    }
    let layout = session
        .layout()?
        .ok_or(EngineError::Unsupported("PAR3 metadata is incomplete"))?;
    let block_size = session
        .set()
        .ok_or(EngineError::Unsupported("PAR3 metadata is incomplete"))?
        .block_size();
    let metadata_hashes: BTreeSet<Fingerprint> = session
        .input
        .packets()
        .filter_map(|packet| packet.metadata().map(|metadata| metadata.hash()))
        .collect();
    // Canonical metadata order: the first complete run at the start of a region.
    let mut metadata: Option<Vec<Vec<u8>>> = None;
    for candidate in candidates {
        let mut packets: Vec<&IngestedPacket> = candidate.packets_of(id).collect();
        packets.sort_by_key(|packet| packet.origin().offset);
        let mut run = Vec::new();
        let mut seen = BTreeSet::new();
        let mut next = None;
        for packet in packets {
            let origin = packet.origin();
            let Some(metadata) = packet.metadata() else {
                break;
            };
            if next.is_some_and(|next| next != origin.offset) {
                break;
            }
            next = Some(origin.offset + origin.length);
            seen.insert(metadata.hash());
            run.push(metadata.to_bytes());
        }
        if seen == metadata_hashes {
            metadata = Some(run);
            break;
        }
    }
    let metadata = metadata.ok_or(EngineError::Unsupported(
        "no region holds a complete metadata run",
    ))?;
    let metadata_bytes: u64 = metadata.iter().map(|packet| packet.len() as u64).sum();
    // Host order is the File packet order of the run. The first file with a
    // given packet hash is the one a hash names, as a forward scan would find.
    let mut by_hash: HashMap<Fingerprint, usize> = HashMap::with_capacity(layout.files().len());
    for (index, file) in layout.files().iter().enumerate() {
        by_hash.entry(file.packet_hash).or_insert(index);
    }
    let mut placed = vec![false; layout.files().len()];
    let mut order = Vec::new();
    for bytes in &metadata {
        let hash: Fingerprint = bytes[8..24].try_into().expect("packet hash");
        if let Some(&file) = by_hash.get(&hash)
            && !std::mem::replace(&mut placed[file], true)
        {
            order.push(file);
        }
    }
    if order.len() != layout.files().len() {
        return Err(EngineError::Unsupported(
            "File packets are not in the metadata run",
        ));
    }
    // Gaps and region layout.
    let recovery_len = packet_len(block_size)?;
    let mut hosts = Vec::new();
    for &file in &order {
        let entry = &layout.files()[file];
        let mut gaps = (0..entry.extents.len())
            .filter(|index| entry.extents.is_unprotected(*index))
            .filter_map(|index| entry.extents.range(index));
        let gap = gaps
            .next()
            .ok_or(EngineError::Unsupported("host has no carrier gap"))?;
        if gaps.next().is_some() {
            return Err(EngineError::Unsupported(
                "host has more than one carrier gap",
            ));
        }
        let (prefix, count) = solve(framing, gap.end - gap.start, metadata_bytes, recovery_len)
            .ok_or(EngineError::Unsupported(
                "carrier gap length fits no framing",
            ))?;
        hosts.push(EmbeddedHostState {
            name: entry.path.clone(),
            path: None,
            matched_by: None,
            file,
            source: None,
            gap: gap.clone(),
            prefix,
            length: entry.len,
            recovery: 0..count,
            complete: false,
            unresolved: Vec::new(),
            packets_found: 0,
            packets_expected: metadata.len() as u64 + count,
            carrier_intact: false,
            framing_intact: None,
        });
    }
    // A Root packet with no children names no host, and so no carrier.
    if hosts.is_empty() {
        return Err(EngineError::Unsupported("set names no host file"));
    }
    // Bind files: recorded name, then recovery indices, then volume number,
    // then a lone host and a lone file.
    // Among files of the recorded name, one carrying this set's packets wins;
    // one carrying only another set's packets is never this set's host.
    // A file with no packets at all is taken by name only in a directory
    // that holds a file carrying this set's packets: one invocation may span
    // several directories, and a same-named file beside another set is not
    // this set's host.
    let tied: BTreeSet<&Path> = candidates
        .iter()
        .filter(|c| c.carries(id))
        .filter_map(|c| c.path.parent())
        .collect();
    let mut used = BTreeSet::new();
    for host in &mut hosts {
        let named = |c: &&Candidate| {
            file_name(&c.path) == Some(host.name.as_str()) && !used.contains(&c.source)
        };
        let ours = |c: &&Candidate| c.carries(id);
        let packetless_beside_ours = |c: &&Candidate| {
            !c.carries_other_than(id) && c.path.parent().is_some_and(|dir| tied.contains(dir))
        };
        if let Some(candidate) = candidates
            .iter()
            .filter(named)
            .find(ours)
            .or_else(|| candidates.iter().filter(named).find(packetless_beside_ours))
        {
            used.insert(candidate.source);
            host.source = Some(candidate.source);
            host.path = Some(candidate.path.clone());
            host.matched_by = Some("name");
        }
    }
    // Recovery index base from a packet found at its slot in a host bound
    // by name; without one, indices start at zero.
    let mut first = None;
    'base: for (position, host) in hosts.iter().enumerate() {
        let Some(source) = host.source else { continue };
        let candidate = candidates
            .iter()
            .find(|c| c.source == source)
            .expect("bound");
        let start = host.gap.start + host.prefix + metadata_bytes;
        let before: u64 = hosts[..position].iter().map(|host| host.recovery.end).sum();
        for packet in candidate.packets_of(id) {
            let Some(PayloadKind::Recovery { index, .. }) = packet.payload().map(|p| p.kind())
            else {
                continue;
            };
            let offset = packet.origin().offset;
            if offset >= start && (offset - start).is_multiple_of(recovery_len) {
                let slot = (offset - start) / recovery_len;
                // An authenticated packet may still carry any index: the
                // arithmetic is checked, never wrapped.
                let earlier = before
                    .checked_add(slot)
                    .ok_or(EngineError::Unsupported("recovery index out of range"))?;
                if slot < host.recovery.end && index >= earlier {
                    first = Some(index - earlier);
                    break 'base;
                }
            }
        }
    }
    let counts: Vec<u64> = hosts.iter().map(|host| host.recovery.end).collect();
    for (host, range) in hosts
        .iter_mut()
        .zip(recovery_ranges(first.unwrap_or(0), &counts)?)
    {
        host.recovery = range;
    }
    for host in hosts.iter_mut().filter(|host| host.source.is_none()) {
        let by_recovery = candidates.iter().find(|c| {
            !used.contains(&c.source)
                && c.packets_of(id).any(|p| {
                    matches!(p.payload().map(|p| p.kind()),
                        Some(PayloadKind::Recovery { index, .. }) if host.recovery.contains(&index))
                })
        });
        if let Some(candidate) = by_recovery {
            used.insert(candidate.source);
            host.source = Some(candidate.source);
            host.path = Some(candidate.path.clone());
            host.matched_by = Some("recovery indices");
        }
    }
    let volume_set = hosts.len() > 1;
    for (position, host) in hosts.iter_mut().enumerate() {
        if host.source.is_some() || !volume_set {
            continue;
        }
        let snapshot_len = |c: &Candidate| access.snapshot(c.source).ok().flatten().map(|s| s.len);
        if let Some(candidate) = candidates.iter().find(|c| {
            !used.contains(&c.source)
                && c.volume == Some(position as u64)
                && snapshot_len(c) == Some(host.length)
                // As for names: a file carrying only another set's packets
                // is never this set's host.
                && (c.carries(id) || !c.carries_other_than(id))
        }) {
            used.insert(candidate.source);
            host.source = Some(candidate.source);
            host.path = Some(candidate.path.clone());
            host.matched_by = Some("volume number");
        }
    }
    if hosts.len() == 1 && hosts[0].source.is_none() {
        let free: Vec<_> = candidates
            .iter()
            .filter(|c| !used.contains(&c.source) && c.carries(id))
            .collect();
        if let [candidate] = free.as_slice() {
            hosts[0].source = Some(candidate.source);
            hosts[0].path = Some(candidate.path.clone());
            hosts[0].matched_by = Some("only file");
        }
    }
    for host in &hosts {
        if let Some(source) = host.source {
            session.bind_file(&host.name, source)?;
        }
    }
    let assessment = session.assess()?;
    let status = assessment.status;
    let lost_blocks = assessment.lost_blocks.len() as u64;
    let additional = assessment.requirements.iter().map(|r| r.additional).sum();
    let recovery_available = assessment.recovery.len() as u64;
    let files = assessment.files.clone();
    for host in &mut hosts {
        let assessed = files
            .iter()
            .find(|file| file.path == host.name)
            .ok_or(EngineError::InvalidState("assessed host"))?;
        host.complete = assessed.complete && host.source.is_some();
        host.unresolved = if host.source.is_some() {
            assessed.unresolved.clone()
        } else {
            std::iter::once(0..host.length).collect()
        };
        let Some(source) = host.source else { continue };
        let candidate = candidates
            .iter()
            .find(|c| c.source == source)
            .expect("bound");
        // One pass over the host's packets indexes them by where they sit,
        // so each expected slot is a lookup rather than a scan: a host with
        // many small recovery packets stays linear.
        let mut hashes_at = BTreeSet::new();
        let mut recovery_at = BTreeSet::new();
        for p in candidate.packets_of(id) {
            let offset = p.origin().offset;
            hashes_at.insert((offset, p.hash()));
            if let Some(PayloadKind::Recovery { index, .. }) = p.payload().map(|p| p.kind()) {
                recovery_at.insert((offset, index));
            }
        }
        let at = host.gap.start + host.prefix;
        let mut found = 0;
        let mut offset = at;
        for bytes in &metadata {
            let hash: Fingerprint = bytes[8..24].try_into().expect("hash");
            if hashes_at.contains(&(offset, hash)) {
                found += 1;
            }
            offset += bytes.len() as u64;
        }
        for index in host.recovery.clone() {
            if recovery_at.contains(&(offset, index)) {
                found += 1;
            }
            offset += recovery_len;
        }
        host.packets_found = found;
        let snapshot = access.snapshot(source)?;
        host.carrier_intact = found == host.packets_expected
            && snapshot.is_some_and(|snapshot| snapshot.len == host.length);
        // The framing is rebuilt from the host's protected bytes, so it is
        // checked only against a host whose protected bytes are verified.
        if host.complete && host.carrier_intact {
            let path = host.path.as_deref().expect("bound");
            let carrier = host.gap.end - host.gap.start - host.prefix;
            host.framing_intact = match framing.prefix(path, carrier)? {
                None => None,
                Some(expected) if expected.len() as u64 != host.prefix => Some(false),
                Some(expected) => {
                    let mut actual = vec![0; expected.len()];
                    Some(
                        read_exact_at(
                            &options.diagnostics,
                            access.as_ref(),
                            source,
                            host.gap.start,
                            &mut actual,
                        )
                        .is_ok()
                            && actual == expected,
                    )
                }
            };
        }
    }
    Ok(EmbeddedSet {
        id,
        hosts,
        status,
        lost_blocks,
        additional,
        recovery_available,
        session,
        metadata,
    })
}
/// The length of one Recovery Data packet for `block_size`, refused when the
/// Start packet records a block size too large for that length to exist.
pub(crate) fn packet_len(block_size: u64) -> EngineResult<u64> {
    block_size
        .checked_add(RECOVERY_OVERHEAD)
        .ok_or(EngineError::Unsupported(
            "block size too large for a recovery packet",
        ))
}

/// The framing length and recovery count that fill a gap of `gap` bytes, if
/// any: the shortest framing `prefix` the caller says fits the remaining
/// carrier, leaving a carrier of whole packets.
fn solve(framing: &dyn CarrierFraming, gap: u64, metadata: u64, packet: u64) -> Option<(u64, u64)> {
    if packet == 0 {
        return None;
    }
    for prefix in 0..=MAX_FRAMING {
        let Some(carrier) = gap.checked_sub(prefix) else {
            break;
        };
        let Some(recovery) = carrier.checked_sub(metadata) else {
            break;
        };
        if recovery % packet != 0 {
            continue;
        }
        if framing.fits(prefix, carrier) {
            return Some((prefix, recovery / packet));
        }
    }
    None
}

/// What self-repair did for one host.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct EmbeddedRepaired {
    /// Recorded host name.
    pub name: String,
    /// Output written.
    pub path: PathBuf,
    /// Protected bytes were rebuilt.
    pub data_rebuilt: bool,
    /// Recovery packets regenerated rather than copied.
    pub regenerated: usize,
    /// Whether the carrier is the authenticated original byte for byte.
    pub restoration: CarrierRestoration,
}

impl EmbeddedSet {
    /// The file name each host has now: its bound file's name, or for a
    /// missing host its recorded name under the stem the bound hosts were
    /// renamed to.
    pub fn current_names(&self) -> Vec<String> {
        let renames: Vec<(String, String)> = self
            .hosts
            .iter()
            .filter_map(|host| {
                let actual = file_name(host.path.as_deref()?)?;
                stem_change(&host.name, actual)
            })
            .collect();
        self.hosts
            .iter()
            .map(|host| {
                if let Some(actual) = host.path.as_deref().and_then(file_name) {
                    return actual.to_owned();
                }
                renames
                    .iter()
                    .find_map(|(old, new)| {
                        host.name
                            .strip_prefix(old.as_str())
                            .map(|rest| format!("{new}{rest}"))
                    })
                    .unwrap_or_else(|| host.name.clone())
            })
            .collect()
    }

    /// Hosts whose protected bytes or region are not intact.
    pub fn needs_repair(&self) -> Vec<usize> {
        (0..self.hosts.len())
            .filter(|&index| !self.hosts[index].complete || !self.hosts[index].region_intact())
            .collect()
    }

    /// Rebuild every host that needs it to `destinations[k]` (absent). Hosts
    /// that are intact are left alone and get no output.
    pub fn repair(
        &mut self,
        destinations: &[PathBuf],
        scratch_directory: &Path,
        framing: &dyn CarrierFraming,
    ) -> EngineResult<Vec<EmbeddedRepaired>> {
        if destinations.len() != self.hosts.len() {
            return Err(EngineError::InvalidState("repair destination count"));
        }
        let needed = self.needs_repair();
        if needed.is_empty() {
            return Ok(Vec::new());
        }
        if !matches!(self.status, RepairStatus::Ready | RepairStatus::Complete) {
            return Err(EngineError::Unsupported(
                "not enough recovery data to repair",
            ));
        }
        for &index in &needed {
            if std::fs::symlink_metadata(&destinations[index]).is_ok() {
                return Err(
                    io::Error::new(io::ErrorKind::AlreadyExists, "repair output exists").into(),
                );
            }
        }
        let options = self.session.options.clone();
        let layout = self.session.layout()?.expect("layout");
        // Stage every file in layout order.
        let mut scratch = Vec::new();
        for host in 0..layout.files().len() {
            scratch.push(crate::session_repair::ScratchFile::new(
                &scratch_directory.join(format!("host-{host}")),
                &options,
            )?);
        }
        let temporaries: Vec<PathBuf> = scratch.iter().map(|file| file.path().to_owned()).collect();
        crate::session_repair::stage_embedded_files(&mut self.session, &temporaries)?;
        let mut disk = DiskSourceAccess::with_options(options.clone());
        for (index, path) in temporaries.iter().enumerate() {
            disk.insert(SourceId(index as u64), path.clone());
        }
        let disk = Arc::new(disk);
        let mut verified = Par3RepairSession::new(self.id, disk.clone(), options.clone())?;
        for packet in self.session.input.packets().filter(|packet| {
            packet.metadata().is_some()
                || packet
                    .payload()
                    .is_some_and(|payload| matches!(payload.kind(), PayloadKind::Recovery { .. }))
        }) {
            verified.merge(packet.clone())?;
        }
        for (index, file) in layout.files().iter().enumerate() {
            verified.bind_file(&file.path, SourceId(index as u64))?;
        }
        if verified.assess()?.status != RepairStatus::Complete {
            return Err(EngineError::InvalidState("rebuilt hosts are incomplete"));
        }
        let size = options.stripe_bytes.min(64 << 10);
        let mut buffer = vec![0; size];
        // Every carrier first: writing a region into a temporary changes the
        // generation `verified` bound, so no carrier can be derived after it.
        let mut carriers = Vec::new();
        let mut prefixes = Vec::new();
        let mut markers = Vec::new();
        let mut reports_pending = Vec::new();
        let generated = (|| -> EngineResult<()> {
            for &index in &needed {
                let host = &self.hosts[index];
                // The framing is rebuilt from the verified protected bytes
                // first, so a host the caller cannot frame writes nothing.
                let carrier_bytes = host.gap.end - host.gap.start - host.prefix;
                let prefix = framing
                    .prefix(&temporaries[host.file], carrier_bytes)?
                    .ok_or(EngineError::Unsupported(
                        "the caller cannot rebuild this host's framing",
                    ))?;
                if prefix.len() as u64 != host.prefix {
                    return Err(EngineError::InvalidState("rebuilt framing length differs"));
                }
                prefixes.push(prefix);
                let marker = crate::session_repair::ScratchFile::new(
                    &scratch_directory.join(format!("carrier-{index}")),
                    &options,
                )?;
                let carrier_path = marker.path().with_extension("carrier");
                markers.push(marker);
                let plan = CarrierPlan::derived(
                    &mut verified,
                    self.metadata.clone(),
                    host.recovery.clone(),
                )?;
                if plan.output_bytes() != host.gap.end - host.gap.start - host.prefix {
                    return Err(EngineError::InvalidState("derived carrier length differs"));
                }
                carriers.push(carrier_path.clone());
                reports_pending.push(plan.execute(
                    &mut verified,
                    &carrier_path,
                    scratch_directory,
                )?);
            }
            Ok(())
        })();
        let mut reports = Vec::new();
        let result = generated.and_then(|()| {
            for (((&index, carrier_path), report), prefix) in needed
                .iter()
                .zip(&carriers)
                .zip(reports_pending.drain(..))
                .zip(&prefixes)
            {
                let host = self.hosts[index].clone();
                let carrier_bytes = host.gap.end - host.gap.start - host.prefix;
                let output = std::fs::OpenOptions::new()
                    .write(true)
                    .open_budgeted(&temporaries[host.file], &options)?;
                output.write_all_at(host.gap.start, prefix)?;
                let carrier = File::open(carrier_path, &options)?;
                let mut at = 0;
                while at < carrier_bytes {
                    options.cancel.check()?;
                    let take = (carrier_bytes - at).min(size as u64) as usize;
                    let read = carrier.read_at(at, &mut buffer[..take])?;
                    if read != take {
                        return Err(EngineError::InvalidState("short carrier read"));
                    }
                    output.write_all_at(host.gap.start + host.prefix + at, &buffer[..take])?;
                    at += take as u64;
                }
                // Positional writes leave nothing buffered to flush.
                drop(output);
                let proof = crate::evidence::verify_source(
                    layout.clone(),
                    host.file,
                    disk.as_ref(),
                    SourceId(host.file as u64),
                    &options,
                )?;
                if !proof.protected_complete() {
                    return Err(EngineError::InvalidState(
                        "repaired host failed verification",
                    ));
                }
                reports.push(EmbeddedRepaired {
                    name: host.name.clone(),
                    path: destinations[index].clone(),
                    data_rebuilt: !host.complete,
                    regenerated: report.recovery_packets,
                    restoration: report.restoration,
                });
            }
            // Every rebuilt host is verified before any is installed, and a
            // failed install removes the destinations this call installed
            // before it, so a failed repair leaves none of them behind.
            let mut installed: Vec<&Path> = Vec::new();
            for (position, &index) in needed.iter().enumerate() {
                let file = self.hosts[index].file;
                let done = injected_install_failure(position)
                    .map_err(EngineError::from)
                    .and_then(|()| install(&temporaries[file], &destinations[index], &options));
                if let Err(error) = done {
                    for path in installed {
                        let _ = std::fs::remove_file(path);
                    }
                    return Err(error);
                }
                installed.push(&destinations[index]);
            }
            Ok(())
        });
        for carrier in &carriers {
            let _ = std::fs::remove_file(carrier);
        }
        drop(markers);
        result.map(|()| reports)
    }

    /// Whether [`Self::remove`] can run: every host present and verified.
    /// Nothing is written.
    ///
    /// # Errors
    ///
    /// [`EngineError::Unsupported`] naming a missing or damaged host.
    pub fn removable(&self) -> EngineResult<()> {
        match self.hosts.iter().find(|host| !host.complete) {
            Some(host) if host.source.is_none() => Err(EngineError::Unsupported(
                "a host is missing; repair before removing",
            )),
            Some(_) => Err(EngineError::Unsupported(
                "a host is damaged; repair before removing",
            )),
            None => Ok(()),
        }
    }

    /// Write every host without its framing and carrier to
    /// `destinations[k]` (absent). The caller's `strip` writes host `k` (the
    /// file at `path`) without them to `out`; every host must be present and
    /// verified, and each output is checked against the length and the
    /// fingerprint the File packet recorded for the original before any is
    /// linked into place.
    pub fn remove(
        &mut self,
        destinations: &[PathBuf],
        strip: &mut dyn FnMut(usize, &Path, &mut dyn Write) -> EngineResult<()>,
    ) -> EngineResult<Vec<PathBuf>> {
        if destinations.len() != self.hosts.len() {
            return Err(EngineError::InvalidState("remove destination count"));
        }
        self.removable()?;
        // Every destination is checked before any is written, so an existing
        // later one does not leave earlier outputs behind.
        if destinations
            .iter()
            .any(|destination| std::fs::symlink_metadata(destination).is_ok())
        {
            return Err(
                io::Error::new(io::ErrorKind::AlreadyExists, "remove output exists").into(),
            );
        }
        let options = self.session.options.clone();
        let layout = self.session.layout()?.expect("layout");
        let size = options.stripe_bytes.min(64 << 10);
        let mut staged = Vec::new();
        let result = (|| -> EngineResult<()> {
            for (index, host) in self.hosts.iter().enumerate() {
                let path = host.path.as_deref().expect("bound");
                let temporary = crate::session_repair::stage_path(&destinations[index], &options)?;
                staged.push(temporary.clone());
                let mut output = std::fs::OpenOptions::new()
                    .write(true)
                    .open_budgeted(&temporary, &options)?;
                let mut hash = FingerprintHasher::new();
                let mut out = BufWriter::with_capacity(size, &mut output);
                let mut counted = Counting {
                    inner: &mut out,
                    written: 0,
                };
                strip(
                    index,
                    path,
                    &mut Hashing {
                        inner: &mut counted,
                        hash: Some(&mut hash),
                    },
                )?;
                let written = counted.written;
                out.flush()?;
                drop(out);
                if written != host.length - (host.gap.end - host.gap.start)
                    || hash.finalize() != layout.files()[host.file].fingerprint
                {
                    return Err(EngineError::InvalidState(
                        "stripped host differs from the original",
                    ));
                }
                output.flush()?;
            }
            // Every output is verified before any is linked into place, and
            // a failed link removes the ones linked before it.
            link_all(&staged, destinations)
        })();
        for path in staged {
            let _ = std::fs::remove_file(path);
        }
        result.map(|()| destinations.to_vec())
    }
}

