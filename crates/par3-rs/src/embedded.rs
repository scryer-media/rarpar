    /// A toy container: the framing is `FRM` and the carrier length, and the
    /// last `TAIL` bytes of a host follow the carrier.
    const TAIL: u64 = 40;
    const FRAME: u64 = 11;

    fn frame(carrier: u64) -> Vec<u8> {
        let mut out = b"FRM".to_vec();
        out.extend_from_slice(&carrier.to_le_bytes());
        out
    }

    struct Toy {
        hosts: Vec<PathBuf>,
        splits: Vec<u64>,
        frame_len: u64,
    }

    impl Toy {
        fn read(&self, host: usize, range: Range<u64>) -> Vec<u8> {
            let bytes = std::fs::read(&self.hosts[host]).unwrap();
            bytes[range.start as usize..range.end as usize].to_vec()
        }
    }

    impl InsertFraming for Toy {
        fn prefix_len(&self, _: usize, _: u64) -> u64 {
            self.frame_len
        }
        fn write_body(&mut self, host: usize, _: u64, out: &mut dyn Write) -> io::Result<()> {
            out.write_all(&self.read(host, 0..self.splits[host]))
        }
        fn write_prefix(&mut self, _: usize, carrier: u64, out: &mut dyn Write) -> io::Result<()> {
            out.write_all(&frame(carrier))
        }
        fn write_tail(&mut self, host: usize, _: u64, out: &mut dyn Write) -> io::Result<()> {
            let len = std::fs::metadata(&self.hosts[host]).unwrap().len();
            out.write_all(&self.read(host, self.splits[host]..len))
        }
    }

    /// Opens the toy container; `framed` false plays a caller without a key.
    struct ToyOpen {
        framed: bool,
    }

    impl CarrierFraming for ToyOpen {
        fn fits(&self, prefix: u64, _: u64) -> bool {
            prefix == FRAME
        }
        fn prefix(&self, _: &Path, carrier: u64) -> EngineResult<Option<Vec<u8>>> {
            Ok(self.framed.then(|| frame(carrier)))
        }
        fn locate(&self, file: &Path) -> CarrierHint {
            let volume = file_name(file)
                .and_then(|name| name.rsplit_once(".part"))
                .and_then(|(_, rest)| rest.split('.').next()?.parse::<u64>().ok())
                .map(|part| part - 1);
            CarrierHint {
                volume,
                carrier_from: None,
            }
        }
    }

    const FRAMED: ToyOpen = ToyOpen { framed: true };

    fn host_bytes(seed: u8) -> Vec<u8> {
        (0..3000u32)
            .map(|index| (index as u8).wrapping_mul(31).wrapping_add(seed))
            .collect()
    }

    fn scratch_dir(label: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("par3-embedded-{label}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn describe(paths: &[PathBuf]) -> (Vec<EmbeddedHost>, Toy) {
        let options = ExecutionOptions::default();
        let hosts: Vec<EmbeddedHost> = paths
            .iter()
            .map(|path| {
                let mut host = EmbeddedHost::new(path, file_name(path).unwrap(), &options).unwrap();
                host.split = host.len() - TAIL;
                host
            })
            .collect();
        let toy = Toy {
            hosts: paths.to_vec(),
            splits: hosts.iter().map(|host| host.split).collect(),
            frame_len: FRAME,
        };
        (hosts, toy)
    }

    fn creation(count: u64) -> CreationOptions {
        CreationOptions {
            block_size: 256,
            recovery_count: count,
            ..CreationOptions::default()
        }
    }

    /// Write toy hosts `names` into `dir/original`, insert one set over them
    /// (or one set per host when `independent`), and return the inserted
    /// files, written into `dir`.
    fn insert_toy(dir: &Path, names: &[&str], seed: u8, independent: bool) -> Vec<PathBuf> {
        let originals = dir.join("original");
        let scratch = dir.join("scratch");
        std::fs::create_dir_all(&originals).unwrap();
        std::fs::create_dir_all(&scratch).unwrap();
        let paths: Vec<PathBuf> = names
            .iter()
            .enumerate()
            .map(|(index, name)| {
                let path = originals.join(name);
                std::fs::write(&path, host_bytes(seed + index as u8)).unwrap();
                path
            })
            .collect();
        let (hosts, mut toy) = describe(&paths);
        let outputs: Vec<PathBuf> = names.iter().map(|name| dir.join(name)).collect();
        if independent {
            for (index, (host, output)) in hosts.iter().zip(&outputs).enumerate() {
                let mut one = Toy {
                    hosts: vec![toy.hosts[index].clone()],
                    splits: vec![toy.splits[index]],
                    frame_len: FRAME,
                };
                insert_set(
                    std::slice::from_ref(host),
                    std::slice::from_ref(output),
                    &[2],
                    creation(2),
                    &scratch,
                    &mut one,
                )
                .unwrap();
            }
        } else {
            let total = 2 * names.len() as u64;
            let counts = placement_counts(Placement::Spread, names.len(), total).unwrap();
            insert_set(
                &hosts,
                &outputs,
                &counts,
                creation(total),
                &scratch,
                &mut toy,
            )
            .unwrap();
        }
        outputs
    }

    fn strip_toy(
        set: &EmbeddedSet,
    ) -> impl FnMut(usize, &Path, &mut dyn Write) -> EngineResult<()> + use<> {
        let gaps: Vec<Range<u64>> = set.hosts.iter().map(|host| host.gap.clone()).collect();
        move |index, path, out| {
            let bytes = std::fs::read(path)?;
            out.write_all(&bytes[..gaps[index].start as usize])?;
            out.write_all(&bytes[gaps[index].end as usize..])?;
            Ok(())
        }
    }

