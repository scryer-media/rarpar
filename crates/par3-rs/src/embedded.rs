        FAIL_INSTALL_AT.with(|at| at.set(None));
        assert!(failed.is_err());
        for output in &outputs {
            assert!(!output.exists(), "{} is left behind", output.display());
        }
        let inserted =
            insert_set(&hosts, &outputs, &[2, 2], creation(4), &scratch, &mut toy).unwrap();
