//! Embedded carrier sets: PAR3 protection carried inside host files whose
//! container format this crate does not know.
//!
//! **Experimental.** The carrier layout is not part of the PAR3 specification
//! yet; it may change before it is stable, and carriers written by this
//! version may not verify with a later one.
//!
//! A caller that understands a container (an archive format, say) describes
//! each host file to this module by three things: where in the file the
//! carrier goes (the *split*), how many bytes of the caller's own framing
//! precede a carrier of a given length, and those framing bytes. This module
//! plans one PAR3 input set over the hosts, writes each carrier, verifies,
//! repairs and removes — and never reads or writes the container's
//! structure itself. The caller writes the host bytes around the carrier
//! ([`InsertFraming`]) and rebuilds its framing on repair
//! ([`CarrierFraming`]).
//!
//! Each host `k` becomes one File packet: its bytes before the split
//! (protected), one unprotected chunk — the caller's framing followed by
//! the carrier — and its bytes from the split on (protected). The File
//! packet's fingerprint covers the host as it was before insertion. Every
//! carrier holds the whole metadata followed by a contiguous range of
//! Recovery Data packets; ranges are assigned in host order. Because the
//! layout is fixed by rule, a carrier can be regenerated byte for byte from
//! the metadata of any other carrier and the protected data.

