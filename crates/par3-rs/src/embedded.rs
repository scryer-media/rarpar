    /// A repair of two damaged hosts whose second install fails leaves
    /// neither destination behind, so the same repair can be retried.
    #[test]
    fn a_failed_later_repair_install_leaves_no_destination_behind() {
        let dir = scratch_dir("repair-rollback");
        let inserted = insert_toy(&dir, &["godwit.part1.bin", "godwit.part2.bin"], 100, false);
        for path in &inserted {
            let mut bytes = std::fs::read(path).unwrap();
            bytes[100] ^= 0x5a;
            std::fs::write(path, bytes).unwrap();
        }
        let out = dir.join("repaired");
        let work = dir.join("work");
        std::fs::create_dir_all(&out).unwrap();
        std::fs::create_dir_all(&work).unwrap();
        let destinations = [out.join("godwit.part1.bin"), out.join("godwit.part2.bin")];
        let open_set = || {
            open(&inserted, &ExecutionOptions::default(), &FRAMED)
                .unwrap()
                .pop()
                .unwrap()
        };
        let mut set = open_set();
        assert_eq!(set.needs_repair(), vec![0, 1]);
        FAIL_INSTALL_AT.with(|at| at.set(Some(1)));
        let failed = set.repair(&destinations, &work, &FRAMED);
        FAIL_INSTALL_AT.with(|at| at.set(None));
        assert!(failed.is_err());
        for destination in &destinations {
            assert!(
                !destination.exists(),
                "{} is left behind",
                destination.display()
            );
        }
        drop(set);
        let mut set = open_set();
        assert_eq!(set.repair(&destinations, &work, &FRAMED).unwrap().len(), 2);
        drop(set);
        std::fs::remove_dir_all(&dir).unwrap();
    }

