//! PAR-inside for RAR5 archives and RAR5 volume sets.
//!
//! **Experimental.** The region layout is not part of the PAR3 specification
//! yet; it may change before it is stable, and regions written by this version
//! may not verify with a later one.
//!
//! RAR5 framing is read from block headers only: signature, header CRC32,
//! header size, type, flags and data size. Members are never decompressed and
//! no RAR structure is rewritten. Every host file keeps its original bytes in
//! place; the PAR3 carrier occupies one unprotected chunk of the file:
//!
//! - [`Rar5Layout::Trailing`]: after the end-of-archive header (and the zero
//!   padding a non-final volume carries). The archive is untouched.
//! - [`Rar5Layout::Block`]: one header of an unassigned block type with the
//!   skip-if-unknown flag, data area = carrier, placed just before the
//!   end-of-archive header.
//! - [`Rar5Layout::Service`]: one service header named `PAR3` with the
//!   skip-if-unknown flag, data area = carrier, placed the same way.
//!
//! A volume set is one PAR3 input set with one File packet per volume. Every
//! volume carries the whole metadata followed by a contiguous range of
//! Recovery Data packets; ranges are assigned in volume order. Because the
//! layout is fixed by rule, a region can be regenerated byte for byte from
//! the metadata of any other region and the protected data.

