        avx2_emitter::append_muladd_body(&mut normal, 0xA53C, false).unwrap();
        avx2_emitter::append_muladd_body(&mut prefetch, 0xA53C, true).unwrap();
        avx2_emitter::append_muladd_body_optional_prefetch(&mut optional, 0xA53C).unwrap();

        assert_ne!(normal, prefetch);
        assert!(normal.len() < prefetch.len());
