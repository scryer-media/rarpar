//! Single-stream MD5 on x86-64 and little-endian AArch64.
//!
//! # Why this exists
//!
//! Single-stream MD5 is the serial floor of every PAR2 pass: whole-file hashes
//! in verify and create, and packet hashes in volume scans. RustCrypto `md-5`
//! dropped its assembly backend after 0.10.0, and the pure-Rust compression
//! that remains is about 25% slower on x86-64, which par2-rs cannot give up.
//! The previous fix linked `aws-lc-sys` for its assembly MD5, but that pulled
//! a whole C crypto library and its build into the crate for one small block
//! function, and the direct `aws-lc-sys` requirement gave consuming
//! applications dependency-resolution trouble: `aws-lc-sys` versions its
//! `links` key, so a requirement that did not match the version their own
//! `aws-lc-rs` linked put a second AWS-LC build in their graph. Carrying the
//! block function here keeps the speed and removes the library. Targets the
//! assembly does not cover use `md-5`.
//!
//! # Origin
//!
//! The block functions are AWS-LC's MD5 assembly carried into `asm!` so the
//! crate links no C or assembly library:
//!
//! - x86-64: `crypto/fipsmodule/md5/asm/md5-x86_64.pl`, by Marc Bevand,
//!   released into the public domain. `%ebx` holds B in the original; Rust
//!   reserves `rbx` for its own use, so B lives in `%r13d` here.
//! - AArch64: `crypto/fipsmodule/md5/asm/md5-armv8.pl`, Copyright 2021-2022
//!   The OpenSSL Project Authors, licensed under the Apache License 2.0
//!   (`LICENSE-APACHE` beside this crate's `LICENSE`). Comments are removed
//!   and `x19`, which Rust reserves, is renamed to `x30`.
//!
//! Both bodies are the generated instruction streams with nothing else
//! changed: the prologue and epilogue, which only save registers and load the
//! state, are replaced by the operand lists. Everything outside the block
//! function (buffering, padding, length) is ordinary Rust.

use core::arch::asm;

const INIT: [u32; 4] = [0x6745_2301, 0xefcd_ab89, 0x98ba_dcfe, 0x1032_5476];

/// Streaming MD5 over the assembly block function.
#[derive(Clone)]
pub(crate) struct Md5 {
    state: [u32; 4],
    buffer: [u8; 64],
    buffered: usize,
    length: u64,
}

impl Md5 {
    pub(crate) fn new() -> Self {
        Self {
            state: INIT,
            buffer: [0; 64],
            buffered: 0,
            length: 0,
        }
    }

    pub(crate) fn update(&mut self, mut data: &[u8]) {
        self.length = self.length.wrapping_add(data.len() as u64);
        if self.buffered > 0 {
            let take = (64 - self.buffered).min(data.len());
            self.buffer[self.buffered..self.buffered + take].copy_from_slice(&data[..take]);
            self.buffered += take;
            data = &data[take..];
            if self.buffered < 64 {
                return;
            }
            let block = self.buffer;
            blocks(&mut self.state, &block);
            self.buffered = 0;
        }
        let whole = data.len() & !63;
        blocks(&mut self.state, &data[..whole]);
        let rest = &data[whole..];
        self.buffer[..rest.len()].copy_from_slice(rest);
        self.buffered = rest.len();
    }

    pub(crate) fn finalize(mut self) -> [u8; 16] {
        let bits = self.length.wrapping_mul(8);
        let mut tail = [0u8; 128];
        tail[..self.buffered].copy_from_slice(&self.buffer[..self.buffered]);
        tail[self.buffered] = 0x80;
        let len = if self.buffered < 56 { 64 } else { 128 };
        tail[len - 8..len].copy_from_slice(&bits.to_le_bytes());
        blocks(&mut self.state, &tail[..len]);
        let mut out = [0u8; 16];
        for (chunk, word) in out.chunks_exact_mut(4).zip(self.state) {
            chunk.copy_from_slice(&word.to_le_bytes());
        }
        out
    }
}

/// Runs the block function over `data`, whose length is a multiple of 64.
fn blocks(state: &mut [u32; 4], data: &[u8]) {
    debug_assert_eq!(data.len() % 64, 0);
    // The AArch64 loop counts blocks in a 32-bit register.
    for chunk in data.chunks(64 << 20) {
        let nblocks = chunk.len() / 64;
        if nblocks > 0 {
            // SAFETY: `chunk` holds exactly `nblocks` 64-byte blocks, and the
            // block function reads only those and the four state words.
            unsafe { block_data_order(state, chunk.as_ptr(), nblocks) }
        }
    }
}

